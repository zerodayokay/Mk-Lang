// Why: the archives are binary; a reviewer of a regenerated view, and
// `mk sdk views`, need its inputs, counts and dropped items as text.
//
// What: ManifestText, the views.txt of one target.
//
// How: one block per view in table order: headers, defines, required
// views, inputs and counts (sorted by key), identity, then every dropped
// item with its reason. Nothing in it depends on the generating machine.

package sysview

import (
	"encoding/hex"
	"fmt"
	"maps"
	"slices"
	"strings"
)

// ManifestText is the manifest of target's views: metas and ids in table
// order, dropped[i] the items dropped from view i.
func ManifestText(target string, metas []Meta, ids [][32]byte, dropped [][]Dropped) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# System views for %s, generated by go run ./tools/sysview; do not edit.\n", target)
	kv := func(m map[string]string) string {
		var parts []string
		for _, k := range slices.Sorted(maps.Keys(m)) {
			parts = append(parts, k+"="+m[k])
		}
		return strings.Join(parts, " ")
	}
	for i, m := range metas {
		counts := map[string]string{}
		for k, v := range m.Counts {
			counts[k] = fmt.Sprint(v)
		}
		fmt.Fprintf(&b, "\nview %s\n", m.Name)
		fmt.Fprintf(&b, "  headers   %s\n", strings.Join(m.Headers, " "))
		if len(m.Defines) > 0 {
			fmt.Fprintf(&b, "  defines   %s\n", strings.Join(m.Defines, " "))
		}
		if len(m.Requires) > 0 {
			fmt.Fprintf(&b, "  requires  %s\n", strings.Join(m.Requires, " "))
		}
		fmt.Fprintf(&b, "  inputs    %s\n", kv(m.Inputs))
		fmt.Fprintf(&b, "  counts    %s\n", kv(counts))
		fmt.Fprintf(&b, "  identity  %s\n", hex.EncodeToString(ids[i][:]))
		for _, d := range dropped[i] {
			fmt.Fprintf(&b, "  dropped   %s (%s): %s\n", d.Name, d.C, d.Reason)
		}
	}
	return b.String()
}
