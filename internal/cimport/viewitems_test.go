// Why: a build from a system view must see the items a build from the
// headers would keep; the archive's dependencies are prune's references
// made durable, so the two must agree.
//
// What: TestCImport_ViewItemsLikePrune, TestCImport_ViewItemsShim and
// TestCImport_FoldIsSysview.
//
// How: two bindings in emit's shape (a later one naming the earlier) are
// pruned with PruneAll and extracted from archives ViewItems built, for
// several wanted sets; the kept export lines are compared.

package cimport

import (
	"slices"
	"strings"
	"testing"

	"mk/internal/sysview"
)

const viewBase = `// The C import c.base, generated by mk from its headers (see doc/reference.md).
// It is a view: edit pkg.mk's CImport, never this file.
// headers: base.h

import std.raw

// C: typedef unsigned long DWORD
export type Dword = u32

// C: struct HANDLE__, 4 bytes, align 4
export struct HandleStruct {
    export unused: Dword
}

// C: member unused
export HandleStruct.Unused(&self): Dword {
    unsafe "the member is at byte 0" {
        return raw.Read(raw.PtrCast[HandleStruct, Dword](raw.Of(self)))
    }
}

// C: typedef struct HANDLE__ *HANDLE
export type Handle = *HandleStruct

// C: int CloseHandle(HANDLE)
export extern CloseHandle(h: Handle): i32

// C: enum COLOR
export type Color = i32
// C: COLOR_RED
export const ColorRed: Color = 0

// C: int inl(void)
// static inline: defined by the shim of this package
export extern inl(): i32
`

const viewGfx = `// The C import c.gfx, generated by mk from its headers (see doc/reference.md).
// It is a view: edit pkg.mk's CImport, never this file.
// headers: gfx.h

import c.base

// C: int Present(HANDLE, DWORD)
export extern Present(h: base.Handle, d: base.Dword): i32

// C: GFX_MAX
export const GfxMax: i32 = 4
`

// exportLines are the column-0 export lines of text, sorted.
func exportLines(text string) []string {
	var out []string
	for _, l := range strings.Split(text, "\n") {
		if strings.HasPrefix(l, "export ") {
			out = append(out, l)
		}
	}
	slices.Sort(out)
	return out
}

func TestCImport_ViewItemsLikePrune(t *testing.T) {
	names, texts := []string{"base", "gfx"}, []string{viewBase, viewGfx}
	views, _ := ViewItems(names, texts, nil)
	if !slices.Equal(views[1].Meta.Requires, []string{"base"}) || len(views[0].Meta.Requires) != 0 {
		t.Fatalf("requires %v %v", views[0].Meta.Requires, views[1].Meta.Requires)
	}
	set := sysview.Set{}
	for _, v := range views {
		b, err := sysview.Write(v.Meta, v.Items, sysview.DefaultOptions)
		if err != nil {
			t.Fatal(err)
		}
		a, err := sysview.Open(b)
		if err != nil {
			t.Fatal(err)
		}
		set[v.Meta.Name] = a
	}
	for _, want := range []map[string][]string{
		{"gfx": {"Present"}},
		{"base": {"CloseHandle"}},
		{"base": {"handle_struct"}},
		{"base": {"ColorRed"}, "gfx": {"GfxMax"}},
		{"base": {"Dword", "inl"}},
	} {
		w := Want{}
		for v, ns := range want {
			w[v] = map[string]bool{}
			for _, n := range ns {
				w.Add(v, n)
			}
		}
		pruned := PruneAll(names, texts, w)
		mods, err := sysview.Extract(set, want, false)
		if err != nil {
			t.Fatal(err)
		}
		got := map[string]string{}
		for _, m := range mods {
			got[m.Name] = m.Text
		}
		for i, n := range names {
			p, e := exportLines(pruned[i]), exportLines(got[n])
			if !slices.Equal(p, e) {
				t.Errorf("want %v, view %s:\nprune   %q\nextract %q", want, n, p, e)
			}
		}
	}
}

// TestCImport_ViewItemsShim: an extern only the shim defines is marked to
// drop, with why.
func TestCImport_ViewItemsShim(t *testing.T) {
	views, drop := ViewItems([]string{"base", "gfx"}, []string{viewBase, viewGfx}, []ShimFunc{{Import: 0, Name: "inl", Inline: true}})
	d := drop["base"]
	if len(d) != 1 {
		t.Fatalf("drop %v", drop)
	}
	for i, why := range d {
		if views[0].Items[i].Name != "inl" || !strings.Contains(why, "static inline") {
			t.Errorf("dropped %s: %s", views[0].Items[i].Name, why)
		}
	}
	for _, it := range views[0].Items {
		if it.Name == "HandleStruct" && it.Kind == "method" && !it.Raw {
			t.Error("the accessor does not need std.raw")
		}
	}
}

func TestCImport_FoldIsSysview(t *testing.T) {
	for _, s := range []string{"", "Hwnd", "HWND", "h_wnd", "_x_", "ID3D12Device", "a1_B2"} {
		if fold(s) != sysview.Fold(s) {
			t.Errorf("fold(%q) = %q, sysview.Fold = %q", s, fold(s), sysview.Fold(s))
		}
	}
}
