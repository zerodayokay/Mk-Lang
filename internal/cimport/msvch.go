// Why: the Windows SDK's headers include four headers of the MSVC
// toolset (vcruntime.h, vadefs.h, vcruntime_string.h, excpt.h) that the
// SDK does not ship, and mk must read the SDK without Visual Studio. The
// names those headers give appear in the bindings (size_t is the view's
// SizeT only if it is declared before the SDK's SIZE_T), so the same
// headers must be used on every machine: mk's own, never a toolset's.
//
// What: MicrosoftHeaderNames and MicrosoftHeaders, the four headers'
// text, and the table they are generated from.
//
// How: each header is generated from a short table of what the SDK's
// headers use and do not define themselves: empty or plain macros, the
// pointer-sized and wide-character typedefs, the C11 string functions'
// prototypes, and the structured-exception disposition. Nothing is copied
// from Microsoft's headers; every name is declared from its documented C
// meaning. The headers hold no code.

package cimport

import (
	"fmt"
	"strings"
)

// msvcHeader is one header mk supplies in place of the MSVC toolset's.
type msvcHeader struct {
	name     string
	about    string   // what it declares, for its comment
	includes []string // headers it includes first
	defines  []string // "NAME BODY" or "NAME(params) BODY"; the body may be empty
	types    []msvcType
	protos   []string // function declarations, without the semicolon
}

// msvcType is one typedef, with the macro the SDK tests to learn that it
// is declared ("" for none).
type msvcType struct {
	guard, decl string
}

