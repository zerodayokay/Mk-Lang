// MicrosoftHeaderNames are the headers mk supplies for a Windows SDK
// sysroot, in a fixed order.
var MicrosoftHeaderNames = func() []string {
	var out []string
	for _, h := range msvcHeaders {
		out = append(out, h.name)
	}
	return out
}()

// MicrosoftHeaders are the headers' texts, by file name. They depend on
// nothing but this table, so every machine reads the same.
func MicrosoftHeaders() map[string]string {
	out := map[string]string{}
	for _, h := range msvcHeaders {
		guard := "__MK_" + strings.ToUpper(strings.NewReplacer(".", "_").Replace(h.name))
		var b strings.Builder
		fmt.Fprintf(&b, "/* Generated by mk in place of the MSVC toolset's %s, for reading the Windows SDK's headers:\n   %s. */\n", h.name, h.about)
		fmt.Fprintf(&b, "#ifndef %s\n#define %s\n", guard, guard)
		for _, inc := range h.includes {
			fmt.Fprintf(&b, "#include <%s>\n", inc)
		}
		for _, d := range h.defines {
			fmt.Fprintf(&b, "#define %s\n", d)
		}
		for _, t := range h.types {
			if t.guard == "" {
				fmt.Fprintf(&b, "%s;\n", t.decl)
				continue
			}
			fmt.Fprintf(&b, "#ifndef %s\n#define %s\n%s;\n#endif\n", t.guard, t.guard, t.decl)
		}
		for _, p := range h.protos {
			fmt.Fprintf(&b, "%s;\n", p)
		}
		b.WriteString("#endif\n")
		out[h.name] = b.String()
	}
	return out
}
