// Why: a static inline C function, or a function-like macro with a
// declared signature, has no symbol to link against, so a binding cannot
// call it through extern alone.
//
// What: ShimFunc and shimDefs, one such function's definition; ShimText,
// which writes one generated C file defining each under its C name,
// compiled in the same build graph; KeptShim, the file a build compiles,
// with only the functions its pruned bindings keep; cDecl and join for C
// declarator spelling, shimmable and retWord.
//
// How: the headers are included with every static inline function renamed
// by a #define to __mk_inline_<name>, then each is defined under its C name
// as a call of the renamed one; a macro is first wrapped in a static inline
// function. So the binding's extern names its symbol as every other extern
// does. The translation keeps every function's definition apart, and a
// build defines only those whose externs its pruned bindings declare.

package cimport

import (
	"fmt"
	"strconv"
	"strings"
)

// cDecl spells a C declaration of inner with type t (C11 6.7.6: pointers
// to functions and arrays parenthesised). It reports false for a type with
// no spelling outside its declaration (an unnamed tag).
func cDecl(t *ctype, inner string) (string, bool) {
	if t == nil {
		return "", false
	}
	switch t.kind {
	case tBuiltin:
		if t.name == "unsupported" {
			return "", false
		}
		return join(t.name, inner), true
	case tTypedef:
		return join(t.name, inner), true
	case tRecord, tEnum:
		if t.name == "" {
			return "", false
		}
		kw := "struct "
		if t.kind == tEnum {
			kw = "enum "
		} else if t.union {
			kw = "union "
		}
		return join(kw+t.name, inner), true
	case tPointer:
		if t.elem != nil && (t.elem.kind == tFunc || t.elem.kind == tArray) {
			return cDecl(t.elem, "(*"+inner+")")
		}
		return cDecl(t.elem, "*"+inner)
	case tArray:
		n := ""
		if t.n >= 0 {
			n = strconv.FormatInt(t.n, 10)
		}
		return cDecl(t.elem, inner+"["+n+"]")
	case tFunc:
		var ps []string
		for _, p := range t.params {
			s, ok := cDecl(p, "")
			if !ok {
				return "", false
			}
			ps = append(ps, s)
		}
		if t.variadic {
			ps = append(ps, "...")
		}
		if len(ps) == 0 {
			ps = []string{"void"}
		}
		return cDecl(t.ret, inner+"("+strings.Join(ps, ", ")+")")
	}
	return "", false
}

func join(base, inner string) string {
	if inner == "" {
		return base
	}
	return base + " " + inner
}

// shimmable reports whether the shim can spell f's result and parameters.
func shimmable(ret *ctype, ps []param) bool {
	if _, ok := cDecl(ret, "f"); !ok {
		return false
	}
	for _, p := range ps {
		if _, ok := cDecl(p.t, "x"); !ok {
			return false
		}
	}
	return true
}

// ShimFunc is one function the shim defines under its C name: the extern
// of import Import's binding that names it, and its definition.
type ShimFunc struct {
	Import int    // the index of the import whose binding declares it
	Name   string // the C name, which is the extern's
	// Inline: a static inline function of the headers, renamed to
	// __mk_inline_<Name> before they are included; else a declared macro.
	Inline bool
	Def    string // the definition, whole lines
}

// shimDefs writes the definition of each shim function: a static inline
// function as a call of its renamed self, a macro first wrapped in a static
// inline function, then the name freed for the definition.
func shimDefs(fs []shimFunc) []ShimFunc {
	out := make([]ShimFunc, 0, len(fs))
	for _, f := range fs {
		var b strings.Builder
		var params, args []string
		for i, p := range f.ps {
			n := "a" + strconv.Itoa(i)
			s, _ := cDecl(p.t, n)
			params = append(params, s)
			args = append(args, n)
		}
		if len(params) == 0 {
			params = []string{"void"}
		}
		target := "__mk_inline_" + f.name
		if f.macro {
			head, _ := cDecl(f.ret, "__mk_macro_"+f.name+"("+strings.Join(params, ", ")+")")
			fmt.Fprintf(&b, "static inline %s { %s%s(%s); }\n", head, retWord(f.ret), f.name, strings.Join(args, ", "))
			fmt.Fprintf(&b, "#undef %s\n", f.name)
			target = "__mk_macro_" + f.name
		} else {
			fmt.Fprintf(&b, "#undef %s\n", f.name)
		}
		head, _ := cDecl(f.ret, f.name+"("+strings.Join(params, ", ")+")")
		fmt.Fprintf(&b, "%s { %s%s(%s); }\n", head, retWord(f.ret), target, strings.Join(args, ", "))
		out = append(out, ShimFunc{Import: f.imp, Name: f.name, Inline: !f.macro, Def: b.String()})
	}
	return out
}

// ShimText is the shim file that defines fs: the unit's defines and
// includes with each static inline function of fs renamed, then each
// definition; "" when fs is empty. A static inline function outside fs
// keeps its name and, unused, is never compiled into the object, so it
// can call what nothing links.
func ShimText(imports []Import, fs []ShimFunc) string {
	if len(fs) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("/* Generated by mk: the static inline functions and declared macros of this package's C imports,\n")
	b.WriteString("   defined under their C names (see doc/reference.md). Never part of the repository. */\n")
	for _, f := range fs {
		if f.Inline {
			fmt.Fprintf(&b, "#define %s __mk_inline_%s\n", f.Name, f.Name)
		}
	}
	for _, im := range imports {
		for _, d := range im.Defines {
			name, val, _ := strings.Cut(d, "=")
			if val == "" && !strings.Contains(d, "=") {
				val = "1"
			}
			fmt.Fprintf(&b, "#define %s %s\n", name, val)
		}
		for _, h := range im.Headers {
			fmt.Fprintf(&b, "#include <%s>\n", h)
		}
	}
	for _, f := range fs {
		b.WriteString(f.Def)
	}
	return b.String()
}

// KeptShim is the shim file of imports that defines only the functions of
// fs whose externs the bindings texts (one per import, pruned: PruneAll)
// still declare; "" when they declare none. A build compiles this one, so
// an unused static inline function or macro that calls what nothing links
// never reaches the link, and the object's key (its text) follows the set
// of functions used.
func KeptShim(imports []Import, fs []ShimFunc, texts []string) string {
	declared := make([]map[string]bool, len(texts))
	var kept []ShimFunc
	for _, f := range fs {
		if f.Import < 0 || f.Import >= len(texts) {
			continue
		}
		if declared[f.Import] == nil {
			declared[f.Import] = externFuncs(texts[f.Import])
		}
		if declared[f.Import][f.Name] {
			kept = append(kept, f)
		}
	}
	return ShimText(imports, kept)
}

// externFuncs are the names of the extern functions a binding text
// declares: its column-0 "export extern NAME(" lines. A pruned binding is
// mostly blank lines, so the scan visits only the kept ones.
func externFuncs(text string) map[string]bool {
	const mark = "\nexport extern "
	out := map[string]bool{}
	for i := strings.Index(text, mark); i >= 0; {
		rest := text[i+len(mark):]
		line, _, _ := strings.Cut(rest, "\n")
		if name, _, ok := strings.Cut(line, "("); ok && !strings.ContainsAny(name, " :") {
			out[name] = true
		}
		j := strings.Index(rest, mark)
		if j < 0 {
			break
		}
		i += len(mark) + j
	}
	return out
}

// retWord is "return " unless the function returns void.
func retWord(t *ctype) string {
	if t != nil && t.kind == tBuiltin && t.name == "void" {
		return ""
	}
	return "return "
}
