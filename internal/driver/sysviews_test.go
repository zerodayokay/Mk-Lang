const fakeWindowsView = `// The C import c.windows, generated by mk from its headers (see doc/reference.md).
// headers: windows.h

import std.raw

// C: typedef unsigned long DWORD
export type Dword = u32

// C: DWORD GetCurrentProcessId(void)
export extern GetCurrentProcessId(): Dword

// C: struct HWND__, 4 bytes, align 4
export struct HwndStruct {
    export unused: i32
}

// C: member unused
export HwndStruct.Unused(&self): i32 {
    unsafe "the member is at byte 0" {
        return raw.Read(raw.PtrCast[HwndStruct, i32](raw.Of(self)))
    }
}

// C: typedef struct HWND__ *HWND
export type Hwnd = *HwndStruct

// C: BOOL DestroyWindow(HWND)
export extern DestroyWindow(h: Hwnd): i32

// C: struct WNDCLASS, 8 bytes, align 8
export struct Wndclass {
    export lpfn_wnd_proc: ?fn(Hwnd): i32
}

// C: extern int mkGlobalCount
export extern var mkGlobalCount: i32

// C: UNUSED_CONST
export const UnusedConst: i32 = 7
`

const fakeDxgiView = `// The C import c.dxgi, generated by mk from its headers (see doc/reference.md).
// headers: dxgi1_6.h

import c.windows

// C: int CreateFactory(HWND)
export extern CreateFactory(h: windows.Hwnd): i32
`

// fakeSysViews serves the fake windows and dxgi views for x86_64-windows,
// and nothing else.
func fakeSysViews(t testing.TB) func(target, name string) ([]byte, bool) {
	views, drop := cimport.ViewItems([]string{"windows", "dxgi"}, []string{fakeWindowsView, fakeDxgiView}, nil)
	if len(drop) != 0 {
		t.Fatalf("drop %v", drop)
	}
	data := map[string][]byte{}
	for _, v := range views {
		v.Meta.Target = "x86_64-windows"
		v.Meta.Headers = []string{v.Meta.Name + ".h"}
		v.Meta.Inputs = map[string]string{"windows-sdk": "10.0.0.0-fake"}
		b, err := sysview.Write(v.Meta, v.Items, sysview.DefaultOptions)
		if err != nil {
			t.Fatal(err)
		}
		data[v.Meta.Name] = b
	}
	return func(target, name string) ([]byte, bool) {
		if target != "x86_64-windows" {
			return nil, false
		}
		b, ok := data[name]
		return b, ok
	}
}

// sysPkg is a package whose module app (unsafe permitted) is main.mk.
func sysPkg(main string, over map[string]string) map[string]string {
	fields := map[string]string{"name": `"p"`, "bins": `[pkg.Bin(name: "p", root: "app", link_script: "", cpu: "", subsystem: "console")]`,
		"unsafe_modules": `["app"]`}
	for k, v := range over {
		fields[k] = v
	}
	return map[string]string{"pkg.mk": manifest(fields), "app/main.mk": main}
}

const sysPidMain = `import c.windows

export Main(sys: &System): WriteError!void {
    var pid: windows.Dword = 0
    unsafe "GetCurrentProcessId takes nothing and cannot fail" {
        pid = windows.GetCurrentProcessId()
    }
    try sys.Print("{pid}\n", (pid))
}
`

// sysSession checks root with the fake views for target.
func sysSession(t *testing.T, root string, target types.Target, mod func(*Config)) (*Session, Result) {
	t.Helper()
	cfg := Config{Root: root, Target: target, CacheDir: t.TempDir()}
	cfg.TestHooks.SysViews = fakeSysViews(t)
	if mod != nil {
		mod(&cfg)
	}
	s, err := NewSession(cfg)
	if err != nil {
		t.Fatal(err)
	}
	return s, s.Check()
}

// sysText is the text of view name's module in s, "" when there is none.
func sysText(s *Session, name string) string {
	if s.w.sysviews == nil || s.w.sysviews.mods[name] == nil {
		return ""
	}
	m := s.w.sysviews.mods[name]
	return m.tree.mem[m.files[0].rel]
}

func TestSysView_Resolves(t *testing.T) {
	s, r := sysSession(t, writeTree(t, sysPkg(sysPidMain, nil)), types.X86_64Windows, nil)
	clean(t, r)
	text := sysText(s, "windows")
	for _, want := range []string{"export extern GetCurrentProcessId(): Dword", "export type Dword = u32"} {
		if !strings.Contains(text, want) {
			t.Errorf("the view lacks %q:\n%s", want, text)
		}
	}
	for _, not := range []string{"DestroyWindow", "UnusedConst", "import std.raw", "HwndStruct"} {
		if strings.Contains(text, not) {
			t.Errorf("the view holds %q, which the program does not use:\n%s", not, text)
		}
	}
	m := s.w.sysviews.mods["windows"]
	if !m.cimport || !m.unsafe || m.std || !m.sysview || m.path != "c.sys.windows" {
		t.Errorf("marks: cimport %v unsafe %v std %v path %s", m.cimport, m.unsafe, m.std, m.path)
	}
	if len(s.w.sysviews.mods) != 1 {
		t.Errorf("modules %v", s.w.sysviews.mods)
	}
}

// TestSysView_RequiredView: an item of dxgi that names windows.Hwnd brings
// windows' Hwnd and what it needs, and only that.
func TestSysView_RequiredView(t *testing.T) {
	user := "import c.dxgi\nimport c.windows\nimport std.raw\n\nexport Main(sys: &System): WriteError!void {\n    var n: i32 = 0\n" +
		"    unsafe \"test\" {\n        h: windows.Hwnd = raw.Null[windows.HwndStruct]()\n        n = dxgi.CreateFactory(h)\n    }\n    try sys.Print(\"{n}\\n\", (n))\n}\n"
	s, r := sysSession(t, writeTree(t, sysPkg(user, nil)), types.X86_64Windows, nil)
	clean(t, r)
	w := sysText(s, "windows")
	if !strings.Contains(w, "export type Hwnd = *HwndStruct") || !strings.Contains(w, "export HwndStruct.Unused(") || strings.Contains(w, "GetCurrentProcessId") {
		t.Errorf("windows:\n%s", w)
	}
	if d := sysText(s, "dxgi"); !strings.Contains(d, "\nimport c.windows\n") || !strings.Contains(d, "CreateFactory") {
		t.Errorf("dxgi:\n%s", d)
	}
	// dxgi alone, with no import of c.windows in the program, still brings
	// windows' items.
	only := "import c.dxgi\n\nexport Main(sys: &System): WriteError!void {\n    try sys.Print(\"{x}\\n\", (x: 1))\n    _ = dxgi.CreateFactory\n}\n"
	s, _ = sysSession(t, writeTree(t, sysPkg(only, nil)), types.X86_64Windows, nil)
	if !strings.Contains(sysText(s, "windows"), "export type Hwnd") {
		t.Errorf("windows without its own import:\n%s", sysText(s, "windows"))
	}
}

// TestSysView_ManifestWins: a pkg.CImport named windows is the package's
// c.windows; no view is formed.
func TestSysView_ManifestWins(t *testing.T) {
	needTools(t)
	main := "import c.windows\n\nexport Main(sys: &System): WriteError!void {\n    try sys.Print(\"{x}\\n\", (x: windows.OwnOnly))\n}\n"
	files := sysPkg(main, map[string]string{"c_imports": `[pkg.CImport(name: "windows", headers: ["mk_absent_own.h"], defines: [], macros: [], vendor: true, include_dirs: [])]`})
	view := "// own\n\n// C: OWN_ONLY\nexport const OwnOnly: i32 = 5\n"
	files["gen/x86_64-windows/c/windows.mk"] = string(cViewBytes(view, "x86_64-windows"))
	s, r := sysSession(t, writeTree(t, files), types.X86_64Windows, nil)
	clean(t, r)
	if s.w.sysviews.mods != nil {
		t.Errorf("a view was formed: %v", s.w.sysviews.mods)
	}
}

func TestSysView_NoCImportHint(t *testing.T) {
	_, r := sysSession(t, writeTree(t, sysPkg("import c.nothing\n\nexport Main(sys: &System) {\n}\n", nil)), types.X86_64Windows, nil)
	expectLines(t, r, "app/main.mk:1:8:E0202")
	if len(r.Report.Diags) == 1 {
		d := r.Report.Diags[0].Diag
		if fact(d, "reason") != "no-cimport" || !strings.Contains(d.Message, "c.windows, c.dxgi") || !strings.Contains(d.Message, "mk sdk views") {
			t.Errorf("%s: %s", fact(d, "reason"), d.Message)
		}
	}
}

