// Why: `import c.<view>` must resolve with no SDK and no Clang, in the
// order the reference gives, keep every C-import rule, and leave a program
// that names no view as it was; CI's runners have no SDK, so these run on
// small fake views built here.
//
// What: fakeSysViews and the resolution tests: TestSysView_Resolves,
// _RequiredView, _ManifestWins, _NoCImportHint, _MissingArchive,
// _FnPointer, _ExternVar, _StdModule (not late, one identity with the
// package), _TextStable and _Cache.
//
// How: two views in emit's shape (windows, and dxgi requiring it) are cut
// by cimport.ViewItems and written as archives, served through
// TestHooks.SysViews.

package driver

