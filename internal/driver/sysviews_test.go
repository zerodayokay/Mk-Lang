// TestSysView_FnPointer: reading a view struct's C function pointer outside
// unsafe is E1101, from a package and from a std module.
func TestSysView_FnPointer(t *testing.T) {
	user := "import c.windows\nimport std.mem\n\nexport Main(sys: &System): WriteError!void {\n" +
		"    wc := mem.Zeroed[windows.Wndclass]()\n    f := wc.lpfn_wnd_proc\n    _ = f\n}\n"
	_, r := sysSession(t, writeTree(t, sysPkg(user, nil)), types.X86_64Windows, nil)
	expectLines(t, r, "app/main.mk:6:10:E1101")
	std := realStdWith(t, map[string]string{"gfxprobe/probe.mk": "import c.windows\nimport std.mem\n\n" +
		"export Proc(): bool {\n    wc := mem.Zeroed[windows.Wndclass]()\n    f := wc.lpfn_wnd_proc\n    return f.IsNone()\n}\n"}, "gfxprobe")
	main := "import std.gfxprobe\n\nexport Main(sys: &System): WriteError!void {\n    try sys.Print(\"{x}\\n\", (x: gfxprobe.Proc()))\n}\n"
	_, r = sysSession(t, writeTree(t, sysPkg(main, nil)), types.X86_64Windows, func(c *Config) { c.StdDir = std })
	expectLines(t, r, "std/gfxprobe/probe.mk:6:10:E1101")
}

// TestSysView_ExternVar: a view's extern var is C's: the build never
// defines it, whether a package or a std module names it.
func TestSysView_ExternVar(t *testing.T) {
	user := "import c.windows\n\nexport Main(sys: &System): WriteError!void {\n    var n: i32 = 0\n" +
		"    unsafe \"test\" {\n        n = *(&windows.mkGlobalCount)\n    }\n    try sys.Print(\"{n}\\n\", (n))\n}\n"
	std := realStdWith(t, map[string]string{"gfxprobe/probe.mk": "import c.windows\n\nexport Count(): i32 {\n" +
		"    unsafe \"test\" {\n        return *(&windows.mkGlobalCount)\n    }\n}\n"}, "gfxprobe")
	for _, c := range []struct {
		name, main, std string
	}{{"package", user, ""}, {"std", "import std.gfxprobe\n\nexport Main(sys: &System): WriteError!void {\n    try sys.Print(\"{x}\\n\", (x: gfxprobe.Count()))\n}\n", std}} {
		s, r := sysSession(t, writeTree(t, sysPkg(c.main, nil)), types.X86_64Windows, func(cfg *Config) { cfg.StdDir = c.std })
		clean(t, r)
		id, ok := s.w.items.ByKey(types.ItemKey("c.sys.windows", "mkGlobalCount"))
		if !ok {
			t.Fatalf("%s: no item c.sys.windows.mkGlobalCount", c.name)
		}
		if s.w.definesVar(id) {
			t.Errorf("%s: the build defines the view's extern var", c.name)
		}
	}
}

// TestSysView_StdModule: a std module that imports a view is no late
// module, checks under a lazy and a full std, and its windows.Hwnd is the
// package's.
func TestSysView_StdModule(t *testing.T) {
	std := realStdWith(t, map[string]string{"gfxprobe/probe.mk": "import c.windows\n\n" +
		"export Close(h: windows.Hwnd): i32 {\n    unsafe \"DestroyWindow takes any handle\" {\n        return windows.DestroyWindow(h)\n    }\n}\n"}, "gfxprobe")
	main := "import c.windows\nimport std.gfxprobe\nimport std.raw\n\nNull(): windows.Hwnd {\n    unsafe \"test\" {\n" +
		"        return raw.Null[windows.HwndStruct]()\n    }\n}\n\nexport Main(sys: &System): WriteError!void {\n" +
		"    try sys.Print(\"{x}\\n\", (x: gfxprobe.Close(Null())))\n}\n"
	for _, lazy := range []bool{false, true} {
		s, r := sysSession(t, writeTree(t, sysPkg(main, nil)), types.X86_64Windows, func(c *Config) { c.StdDir, c.LazyStd = std, lazy })
		clean(t, r)
		if m := s.stdB.byName["std.gfxprobe"]; m == nil || m.late {
			t.Errorf("lazy %v: std.gfxprobe is late or missing", lazy)
		}
		if len(s.w.sysviews.mods) != 1 {
			t.Errorf("lazy %v: views %v", lazy, s.w.sysviews.mods)
		}
		pkg, result, err := s.Doc(DocOptions{Std: "std"})
		if err != nil || pkg == nil {
			t.Fatalf("lazy %v: documentation: %v\n%s", lazy, err, result.Report.Text(result.Sources))
		}
		for _, mod := range pkg.Modules {
			if strings.HasPrefix(mod.Path, "c.sys.") {
				t.Errorf("lazy %v: std docs include system view %s", lazy, mod.Path)
			}
		}
	}
}

// TestSysView_TextStable: the module text is a function of the names used,
// whatever order the files use them in.
func TestSysView_TextStable(t *testing.T) {
	a := "import c.windows\n\nexport Main(sys: &System): WriteError!void {\n    _ = windows.DestroyWindow\n    _ = windows.GetCurrentProcessId\n}\n"
	b := "import c.windows\n\nexport Main(sys: &System): WriteError!void {\n    _ = windows.GetCurrentProcessId\n    _ = windows.DestroyWindow\n}\n"
	s1, _ := sysSession(t, writeTree(t, sysPkg(a, nil)), types.X86_64Windows, nil)
	s2, _ := sysSession(t, writeTree(t, sysPkg(b, nil)), types.X86_64Windows, nil)
	if t1, t2 := sysText(s1, "windows"), sysText(s2, "windows"); t1 == "" || t1 != t2 {
		t.Errorf("texts differ:\n%s\n---\n%s", t1, t2)
	}
}

// TestSysView_Cache: a second check hits the extraction cache, an edit
// that uses nothing new hits, a new use misses.
func TestSysView_Cache(t *testing.T) {
	dir := writeTree(t, sysPkg(sysPidMain, map[string]string{}))
	cache := t.TempDir()
	run := func() *sysViews {
		cfg := Config{Root: dir, Target: types.X86_64Windows, CacheDir: cache}
		cfg.TestHooks.SysViews = fakeSysViews(t)
		s, err := NewSession(cfg)
		if err != nil {
			t.Fatal(err)
		}
		clean(t, s.Check())
		return s.w.sysviews
	}
	first := run()
	if first.hit {
		t.Fatal("a cold check hit")
	}
	if again := run(); !again.hit || again.key != first.key {
		t.Fatal("a warm check missed")
	}
	writeFiles(t, dir, map[string]string{"app/other.mk": "// nothing of the view\nexport Two(): int {\n    return 2\n}\n"})
	if edit := run(); !edit.hit {
		t.Fatal("an unrelated edit missed")
	}
	writeFiles(t, dir, map[string]string{"app/other.mk": "import c.windows\n\nexport Two(h: windows.Hwnd): i32 {\n    unsafe \"test\" {\n        return windows.DestroyWindow(h)\n    }\n}\n"})
	if use := run(); use.hit || use.key == first.key {
		t.Fatal("a new use hit")
	}
}

