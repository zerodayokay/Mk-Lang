// Why: the HTTP/2 frame header, frame payload and SETTINGS parsers read
// untrusted peer bytes; no input may panic, violate slice bounds, or parse a
// frame that breaks RFC 9113 invariants.
//
// What: FuzzStdHttpH2_Frames, with its driver hh2Serve and fixture hh2Shim.
//
// How: std.http.h2 is std-only, so a fixture file of std.http in a copy of
// std (hh2Shim) holds the driver's body, and a program calls it. One
// long-running release driver answers every input of a fuzz worker ("<len>\n"
// then bytes; answer lines then END). Each input feeds ParseHeader + Parse and
// Settings.Apply / Write* round-trip checks; any broken invariant panics.
//
// Its fuzz targets read untrusted input; tools/gate/safety.go lists each untrusted-input target.

