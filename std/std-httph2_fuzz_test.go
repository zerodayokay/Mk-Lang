const hh2ShimPath = "http/zz_h2fuzz_shim.mk"

const hh2Shim = `// Generated by std/std-httph2_fuzz_test.go: a fixture of its std copy.
//
// Why: std.http.h2 is std-only, so its fuzz driver reaches it through a
// fixture file of std.http.
// What: H2FuzzMain, which answers fuzz inputs on standard input.
// How: byte 0 selects max_frame and from_server; bytes 1.. split into up to
// three frames parsed with ParseHeader + Parse, applying SETTINGS payloads and
// round-tripping fixed/data frames through Write* helpers.

import std.core
import std.http.fields
import std.http.h2
import std.net
import std.net.pipe
import std.rt

Hh2Eq(a: []u8, b: []u8): bool {
    return a.Len() == b.Len() && core.BytesEqual(a, 0, b)
}

Hh2RoundTrip(a: &Arena, f: h2.Frame, max_frame: int): OutOfMemory!void {
    out := try a.Slice[u8](max_frame + 64)
    match f {
        .Data(stream, data, padded, end) {
            _ = padded
            n := h2.WriteData(out, stream, data, end) else { Panic("WriteData failed") }
            h := h2.ParseHeader(out[0..n]).Must()
            back := h2.Parse(&h, out[0..n], max_frame) else { Panic("Data roundtrip failed") }
            match back {
                .Data(stream: bs, data: bd, padded: bp, end: be) {
                    Assert(bs == stream && bp == 0 && be == end && Hh2Eq(bd, data))
                }
                _ { Panic("Data roundtrip kind") }
            }
        }
        .RstStream(stream, code) {
            n := h2.WriteRstStream(out, stream, code) else { Panic("WriteRstStream failed") }
            h := h2.ParseHeader(out[0..n]).Must()
            back := h2.Parse(&h, out[0..n], max_frame) else { Panic("RstStream roundtrip failed") }
            match back {
                .RstStream(stream: bs, code: bc) { Assert(bs == stream && bc == code) }
                _ { Panic("RstStream roundtrip kind") }
            }
        }
        .Ping(ack, data) {
            n := h2.WritePing(out, &data, ack) else { Panic("WritePing failed") }
            h := h2.ParseHeader(out[0..n]).Must()
            back := h2.Parse(&h, out[0..n], max_frame) else { Panic("Ping roundtrip failed") }
            match back {
                .Ping(ack: ba, data: bd) { Assert(ba == ack && Hh2Eq(bd[..], data[..])) }
                _ { Panic("Ping roundtrip kind") }
            }
        }
        .Goaway(last, code, debug) {
            _ = debug
            n := h2.WriteGoaway(out, last, code) else { Panic("WriteGoaway failed") }
            h := h2.ParseHeader(out[0..n]).Must()
            back := h2.Parse(&h, out[0..n], max_frame) else { Panic("Goaway roundtrip failed") }
            match back {
                .Goaway(last: bl, code: bc, debug: bdbg) {
                    _ = bdbg
                    Assert(bl == last && bc == code)
                }
                _ { Panic("Goaway roundtrip kind") }
            }
        }
        .WindowUpdate(stream, increment) {
            n := h2.WriteWindowUpdate(out, stream, increment) else { Panic("WriteWindowUpdate failed") }
            h := h2.ParseHeader(out[0..n]).Must()
            back := h2.Parse(&h, out[0..n], max_frame) else { Panic("WindowUpdate roundtrip failed") }
            match back {
                .WindowUpdate(stream: bs, increment: bi) { Assert(bs == stream && bi == increment) }
                _ { Panic("WindowUpdate roundtrip kind") }
            }
        }
        _ { }
    }
}

Hh2Run(a: &Arena, w: mut Writer, input: []u8): WriteError|OutOfMemory!void {
    if input.Len() < 1 {
        try w.Str("short\n")
        return
    }
    from_server := (input[0] & 1) != 0
    max_frame := if (input[0] & 2) != 0 { 32768 } else { 16384 }
    rest := input[1..]
    var at := 0
    var settings := h2.InitialSettings
    for at < rest.Len() {
        h := h2.ParseHeader(rest[at..]) else {
            try w.Str("tail\n")
            return
        }
        if h.length > rest.Len() - at - 9 {
            // Also exercise Parse mismatch error path safely without panic.
            match h2.Parse(&h, rest[at..], max_frame) {
                ok(_) { Panic("short payload parsed") }
                err(e) { try Print(w, "err {code}\n", (code: e.code)) }
            }
            return
        }
        pkt := rest[at..at + 9 + h.length]
        match h2.Parse(&h, pkt, max_frame) {
            ok(f) {
                try Hh2RoundTrip(a, f, max_frame)
                match f {
                    .Settings(ack, entries) {
                        if !ack {
                            match settings.Apply(entries, from_server) {
                                ok(_) { try w.Str("ok settings\n") }
                                err(e) { try Print(w, "err {code}\n", (code: e.code)) }
                            }
                        } else {
                            try w.Str("ok ack\n")
                        }
                    }
                    _ { try w.Str("ok frame\n") }
                }
            }
            err(e) {
                try Print(w, "err {code}\n", (code: e.code))
            }
        }
        at += 9 + h.length
    }
}

struct Hh2Field {
    name: str
    value: str
}

impl fields.Field for Hh2Field {
    Name(&self): []u8 {
        return self.name.AsBytes()
    }

    Value(&self): []u8 {
        return self.value.AsBytes()
    }

    Sensitive(&self): bool {
        return false
    }
}

Hh2SrvDeliver(st: &Mutex[int], conn: &h2.Conn, r: h2.Request) {
    s := r.stream
    h2.Request(stream: _, head, body) := r
    nc := core.IoMasked(rt.NativeIo())
    var g := st.Lock(nc).Must()
    *g.Mut() += 1
    g.Unlock()
    var empty_hs: [0]Hh2Field = []
    conn.Respond(nc, s, 200, empty_hs[..], true) else {}
    conn.Done(s, head, body)
}

Hh2SrvServeTask(io: Io, conn: &h2.Conn, st: &Mutex[int]) {
    conn.Serve(io, st, Hh2SrvDeliver) else {}
}

Hh2SrvWriterTask(io: Io, conn: &h2.Conn) {
    conn.Writer(io) else {}
}

Hh2SrvDrainTask(io: Io, c: &net.Conn) {
    var buf: [4096]u8 = [0; 4096]
    for {
        n := c.Read(io, mut buf[..]) else {
            return
        }
        if n == 0 {
            return
        }
    }
}

Hh2RunServer(sys: &System, w: mut Writer, input: []u8): WriteError|OutOfMemory!void {
    if input.Len() < 1 {
        try w.Str("short\n")
        return
    }
    a := sys.heap.Alloc()
    (a: srv_c, b: cli_c) := try pipe.ConnPair(sys.heap, 16384)
    lim := h2.Limits(
        streams: 8,
        window: 65535,
        header_bytes: 1024,
        body_bytes: 4096,
        write_limit: core.DurationOf(200_000_000),
        close_limit: core.DurationOf(100_000_000),
        idle_limit: core.DurationOf(20_000_000),
    )
    var empty: [0]u8 = []
    srv_box := h2.Conn.Server(sys.heap, sys.io, srv_c, lim, empty[..]) else {
        srv_c.Abandon()
        cli_c.Abandon()
        try w.Str("err open\n")
        return
    }
    cnt := Mutex[int].New(0)
    scope s := sys.io.Scope() {
        s.CancelAfter(core.DurationOf(500_000_000))
        s.go Hh2SrvServeTask(sys.io, srv_box.Ref(), &cnt)
        s.go Hh2SrvWriterTask(sys.io, srv_box.Ref())
        s.go Hh2SrvDrainTask(sys.io, &cli_c)
        if (input[0] & 1) == 0 {
            var pbuf: [64]u8 = [0; 64]
            (mut pbuf[0..24]).CopyFrom(h2.Preface[..])
            init_s := h2.InitialSettings
            sn := h2.WriteSettings(mut pbuf[24..], &init_s).Must()
            cli_c.WriteAll(sys.io, pbuf[0..24 + sn]) else {}
        }
        if input.Len() > 1 {
            cli_c.WriteAll(sys.io, input[1..]) else {}
        }
        cli_c.Shutdown(sys.io, net.Shutdown.Write) else {}
    }
    cli_c.Abandon()
    srv_box.Take(a).Abandon()
    _ = cnt.Into()
    try w.Str("ok server\n")
}

Hh2CliDriveTask(io: Io, cli: &h2.Conn) {
    cli.Drive(io, core.DurationOf(20_000_000)) else {}
}

Hh2CliReqTask(io: Io, h: &Heap, cli: &h2.Conn) {
    p := fields.Pseudo(method: "GET", scheme: "https", authority: "example.com", path: "/")
    var hs: [0]Hh2Field = []
    ms := cli.TryOpen(io, &p, hs[..], true) else { return }
    sr := ms else { return }
    var ar := Arena.New(h) else {
        cli.Release(sr)
        return
    }
    defer ar.Free()
    _ = cli.Head(&ar, io, sr) else {
        cli.Release(sr)
        return
    }
    var buf: [512]u8 = [0; 512]
    for _ in 0..8 {
        n := cli.Read(io, sr, mut buf[..]) else { break }
        if n == 0 {
            break
        }
    }
    cli.Release(sr)
}

Hh2RunClient(sys: &System, w: mut Writer, input: []u8): WriteError|OutOfMemory!void {
    if input.Len() < 1 {
        try w.Str("short\n")
        return
    }
    a := sys.heap.Alloc()
    (a: srv_c, b: cli_c) := try pipe.ConnPair(sys.heap, 16384)
    lim := h2.Limits(
        streams: 8,
        window: 65535,
        header_bytes: 1024,
        body_bytes: 4096,
        write_limit: core.DurationOf(100_000_000),
        close_limit: core.DurationOf(50_000_000),
        idle_limit: core.DurationOf(20_000_000),
    )
    cli_box := h2.Conn.Client(sys.heap, sys.io, cli_c, lim) else {
        srv_c.Abandon()
        cli_c.Abandon()
        try w.Str("err open\n")
        return
    }
    scope s := sys.io.Scope() {
        s.CancelAfter(core.DurationOf(200_000_000))
        s.go Hh2SrvDrainTask(sys.io, &srv_c)
        if (input[0] & 2) != 0 {
            s.go Hh2CliDriveTask(sys.io, cli_box.Ref())
        } else {
            s.go Hh2CliReqTask(sys.io, sys.heap, cli_box.Ref())
        }
        if (input[0] & 1) == 0 {
            var sbuf: [64]u8 = [0; 64]
            init_s := h2.InitialSettings
            sn := h2.WriteSettings(mut sbuf[..], &init_s).Must()
            an := h2.WriteSettingsAck(mut sbuf[sn..]).Must()
            srv_c.WriteAll(sys.io, sbuf[0..sn + an]) else {}
        }
        if input.Len() > 1 {
            srv_c.WriteAll(sys.io, input[1..]) else {}
        }
        srv_c.Shutdown(sys.io, net.Shutdown.Write) else {}
    }
    srv_c.Abandon()
    cli_box.Take(a).Abandon()
    try w.Str("ok client\n")
}

/// Serves HTTP/2 frame and server fuzz inputs on standard input until EOF.
export H2FuzzMain(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {
    var inp := sys.Stdin()
    var out := sys.Stdout()
    data := try sys.arena.Slice[u8](1 << 16)
    var head: [32]u8 = [0; 32]
    for {
        k := try inp.Until(0x0A, mut head[..])
        if k == 0 {
            return
        }
        var mode: u8 = 0
        var start := 0
        if k >= 2 && (head[0] == b'S' || head[0] == b'C') {
            mode = head[0]
            start = 1
        }
        line := try str.From(head[start..k - 1])
        n := Cast[int](try line.ParseInt())
        got := try inp.ReadAll(mut data[0..n])
        var ar := try Arena.New(sys.heap)
        defer ar.Free()
        if mode == b'S' {
            try Hh2RunServer(sys, mut out, data[0..got])
        } else if mode == b'C' {
            try Hh2RunClient(sys, mut out, data[0..got])
        } else {
            try Hh2Run(&ar, mut out, data[0..got])
        }
        try out.Str("END\n")
        try out.Flush()
    }
}
`

const hh2Serve = "import std.http\n\nexport Main(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {\n    try http.H2FuzzMain(sys)\n}\n"

var hh2Srv struct {
	sync.Mutex
	cmd    *exec.Cmd
	in     io.WriteCloser
	out    *bufio.Reader
	err    *bytes.Buffer
	failed string
}

func hh2AskMode(t *testing.T, prefix string, in []byte) []string {
	t.Helper()
	hh2Srv.Lock()
	defer hh2Srv.Unlock()
	if hh2Srv.failed != "" {
		t.Fatal(hh2Srv.failed)
	}
	if hh2Srv.cmd == nil {
		dir, err := packageTempDir("mkhh2z")
		if err != nil {
			t.Fatal(err)
		}
		stdDir := copyStd(t, dir, map[string]string{hh2ShimPath: hh2Shim})
		if err := os.WriteFile(filepath.Join(dir, "main.mk"), []byte(hh2Serve), 0o644); err != nil {
			t.Fatal(err)
		}
		exe := filepath.Join(dir, "hh2z")
		if runtime.GOOS == "windows" {
			exe += ".exe"
		}
		t.Setenv("MK_CACHE", filepath.Join(dir, "cache"))
		out, status := mkCmd(t, dir, stdDir, "build", "--release", "-o", exe, "main.mk")
		if status != 0 {
			if strings.Contains(out, "no usable LLVM") {
				t.Skipf("needs the LLVM toolchain: %s", out)
			}
			hh2Srv.failed = fmt.Sprintf("mk build: exit %d\n%s", status, out)
			t.Fatal(hh2Srv.failed)
		}
		cmd := exec.Command(exe)
		stdin, err := cmd.StdinPipe()
		if err != nil {
			t.Fatal(err)
		}
		stdout, err := cmd.StdoutPipe()
		if err != nil {
			t.Fatal(err)
		}
		var eb bytes.Buffer
		cmd.Stderr = &eb
		if err := cmd.Start(); err != nil {
			t.Fatal(err)
		}
		hh2Srv.cmd, hh2Srv.in, hh2Srv.out, hh2Srv.err = cmd, stdin, bufio.NewReader(stdout), &eb
	}
	if _, err := fmt.Fprintf(hh2Srv.in, "%s%d\n%s", prefix, len(in), in); err != nil {
		hh2Died(t, in, err)
	}
	var lines []string
	for {
		line, err := hh2Srv.out.ReadString('\n')
		if err != nil {
			hh2Died(t, in, err)
		}
		line = strings.TrimRight(line, "\r\n")
		if line == "END" {
			return lines
		}
		lines = append(lines, line)
	}
}

func hh2Ask(t *testing.T, in []byte) []string {
	t.Helper()
	return hh2AskMode(t, "", in)
}

func hh2Died(t *testing.T, in []byte, err error) {
	t.Helper()
	msg := hh2Srv.err.String()
	hh2Srv.cmd = nil
	t.Fatalf("driver gone on input %x: %v\n%s", in, err, msg)
}

func hh2Stop() {
	hh2Srv.Lock()
	defer hh2Srv.Unlock()
	if hh2Srv.cmd == nil {
		return
	}
	hh2Srv.in.Close()
	_ = hh2Srv.cmd.Wait()
	hh2Srv.cmd = nil
}

func hh2Unhex(s string) []byte {
	b, err := hex.DecodeString(strings.ReplaceAll(s, " ", ""))
	if err != nil {
		panic(err)
	}
	return b
}

var hh2Seeds = []string{
	"00 000000 04 01 00000000",                          // SETTINGS ACK
	"00 000006 04 00 00000000 0002 00000000",            // SETTINGS ENABLE_PUSH=0
	"01 000006 04 00 00000000 0002 00000001",            // server SETTINGS ENABLE_PUSH=1 (err)
	"00 000005 00 01 00000001 68656c6c6f",               // DATA END_STREAM
	"00 000004 00 08 00000001 04 000000",                // DATA PADDED bad pad
	"00 000009 01 2d 00000003 01 80000000 0f 8286 00",   // HEADERS PADDED+PRIORITY
	"00 000005 02 00 00000001 00000000 00",              // PRIORITY
	"00 000004 03 00 00000001 00000008",                 // RST_STREAM
	"00 000008 06 00 00000000 0102030405060708",         // PING
	"00 00000c 07 00 00000000 00000005 00000000 646267", // GOAWAY + debug
	"00 000004 08 00 00000000 00010000",                 // WINDOW_UPDATE
	"00 000002 09 04 00000001 8286",                     // CONTINUATION
	"00 000004 fe 00 00000007 01020304",                 // Unknown frame
}

func FuzzStdHttpH2_Frames(f *testing.F) {
	f.Cleanup(hh2Stop)
	for _, s := range hh2Seeds {
		f.Add(hh2Unhex(s))
	}
	f.Fuzz(func(t *testing.T, in []byte) {
		if len(in) > 32768 {
			in = in[:32768]
		}
		for _, l := range hh2Ask(t, in) {
			if l != "short" && l != "tail" && !strings.HasPrefix(l, "ok ") && !strings.HasPrefix(l, "err ") {
				t.Fatalf("input %x: answer %q", in, l)
			}
		}
	})
}

