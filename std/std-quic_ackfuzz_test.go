// Why: QUIC's AckSet and Recovery process untrusted ACK ranges and packet
// numbers from the network and must never panic, violate the 64-range or
// 256-range caps, or accept unsent/skipped packet numbers on any byte input.
//
// What: FuzzStdQuic_Ack, with its long-running release driver qkAsk and
// temporary shim qkShim inside the copied std directory.
//
// How: each fuzz input encodes a sequence of AckSet and Recovery operations
// (Add, Write, OnSent, OnAck, OnTimeout, Discard) over fuzzed spaces, packet
// numbers, ACK ranges, and simulated clock steps. A broken invariant or panic
// terminates the driver and fails the fuzz test.
//
// Its fuzz targets read untrusted input; tools/gate/safety.go lists each untrusted-input target.

package std

import (
	"bufio"
	"bytes"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"sync"
	"testing"
)

// qkShimPath is the fixture file added to the temporary copy of std.quic.
const qkShimPath = "quic/zz_ackfuzz_shim.mk"

// qkShim drives AckSet and Recovery directly inside std.quic.
const qkShim = `// Generated by std/std-quic_fuzz_test.go: a fixture of its std copy.
//
// Why: AckSet and Recovery are module-private inside std.quic, so the fuzz
// driver reaches them through a fixture in a copy of std.
//
// What: AckFuzzMain, which reads fuzz inputs from stdin and checks AckSet
// and Recovery invariants on every input.
//
// How: reads "<len>\n" followed by <len> bytes, runs the byte stream as an
// opcode script over AckSet and Recovery with a std.sim clock, and writes
// "ok\n" or panics on any invariant violation.

import std.sim
import std.time

QkSpace(b: u8): Space {
    m := b & 3
    if m == 0 {
        return Space.Initial
    }
    if m == 1 {
        return Space.Handshake
    }
    return Space.App
}

QkReadU16(data: []u8, pos: int): int {
    return (int(data[pos]) << 8) | int(data[pos + 1])
}

QkRun(ar: &Arena, h: &Alloc, data: []u8): OutOfMemory!void {
    var s := sim.Sim.New(ar, 1) else {
        return
    }
    defer s.Free()
    var acks := AckSet.New()
    var rec := try Recovery.New(h)
    defer rec.Free(h)

    var out: [256]u8 = [0; 256]
    var acked: [64]SentFrame = [SentFrame(kind: SentKind.Control(index: 0)); 64]
    var lost: [64]SentFrame = [SentFrame(kind: SentKind.Control(index: 0)); 64]
    var i := 0
    for i < data.Len() {
        op := data[i] % 7
        i += 1
        now := time.Now(s.Io())
        if op == 0 && i + 3 <= data.Len() {
            // AckSet.Add + duplicate invariant.
            sp := QkSpace(data[i])
            pn := i64(QkReadU16(data, i + 1)) - 8
            ae := (data[i] & 4) != 0
            i += 3
            prev_floor := acks.Floor(sp)
            ok := acks.Add(sp, pn, ae, now)
            if pn < 0 || pn < prev_floor {
                Assert(!ok)
            }
            if ok {
                Assert(!acks.Add(sp, pn, ae, now))
            }
            Assert(acks.RangeCount(sp) <= 64)
        } else if op == 1 && i + 2 <= data.Len() {
            // AckSet.Write into fuzzed cap.
            sp := QkSpace(data[i])
            cap := int(data[i + 1])
            i += 2
            n := acks.Write(sp, mut out[0..cap], now)
            Assert(n >= 0 && n <= cap)
            if n > 0 {
                Assert(!acks.NeedsAckOnly(sp, now))
            }
        } else if op == 2 && i + 2 <= data.Len() {
            // Recovery.OnSent (optionally skipping a PN first).
            sp := QkSpace(data[i])
            if (data[i] & 8) != 0 {
                skip := rec.NextPn(sp)
                rec.SkipPn(sp, skip)
            }
            pn := rec.NextPn(sp)
            sz := 100 + int(data[i + 1]) * 4
            ae := (data[i] & 4) != 0
            inf := ae || (data[i] & 16) != 0
            i += 2
            fs := [SentFrame(kind: SentKind.Control(index: int(pn & 0xFF)))]
            try rec.OnSent(h, sp, pn, sz, ae, inf, fs[..], now)
            Assert(rec.BytesInFlight() >= 0)
        } else if op == 3 && i + 2 <= data.Len() {
            // Recovery.OnAck with fuzzed range list (including > 256 or invalid PNs).
            sp := QkSpace(data[i])
            cnt := int(data[i + 1])
            i += 2
            var ranges := HeapList[AckRange].New(h)
            defer ranges.Free(h)
            var r := 0
            for r < cnt && i + 4 <= data.Len() {
                lo := i64(QkReadU16(data, i)) - 16
                hi := lo + i64(QkReadU16(data, i + 2) & 0xFF)
                try ranges.Push(h, AckRange(lo: lo, hi: hi))
                i += 4
                r += 1
            }
            if ranges.Len() == 0 && cnt > 0 {
                // Exercise > 256 ranges when high bit set.
                var k := 0
                for k < 260 && k < cnt * 2 {
                    try ranges.Push(h, AckRange(lo: -1, hi: 0))
                    k += 1
                }
            }
            _ = rec.OnAck(sp, ranges.Items(), time.Millis(2), now, mut acked[..], mut lost[..]) else e {
                match e {
                    TransportError(code) { Assert(code == ErrProtocolViolation) }
                    _ { Assert(false) }
                }
                (acked: 0, lost: 0)
            }
            Assert(rec.BytesInFlight() >= 0)
            Assert(rec.Cwnd() >= 2400)
        } else if op == 4 {
            _ = rec.OnTimeout(now, mut lost[..])
            Assert(rec.BytesInFlight() >= 0)
        } else if op == 5 && i < data.Len() {
            sp := QkSpace(data[i])
            i += 1
            rec.Discard(sp)
            Assert(rec.BytesInFlight() >= 0)
        } else if op == 6 && i < data.Len() {
            ms := i64(data[i]) * 5 + 1
            i += 1
            s.Io().Sleep(time.Millis(ms)) else {}
        } else {
            break
        }
    }
}

/// Serves ACK/recovery fuzz inputs on stdin until EOF.
export AckFuzzMain(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {
    var inp := sys.Stdin()
    var out := sys.Stdout()
    data := try sys.arena.Slice[u8](1 << 16)
    var head: [32]u8 = [0; 32]
    h := sys.heap.Alloc()
    for {
        k := try inp.Until(0x0A, mut head[..])
        if k == 0 {
            return
        }
        line := try str.From(head[0..k - 1])
        n := Cast[int](try line.ParseInt())
        got := try inp.ReadAll(mut data[0..n])
        var ar := try Arena.New(sys.heap)
        defer ar.Free()
        try QkRun(&ar, h, data[0..got])
        try out.Str("ok\n")
        try out.Flush()
    }
}
`

const qkServe = "import std.quic\n\nexport Main(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {\n    try quic.AckFuzzMain(sys)\n}\n"

var qkSrv struct {
	sync.Mutex
	cmd    *exec.Cmd
	in     io.WriteCloser
	out    *bufio.Reader
	err    *bytes.Buffer
	failed string
}

func qkAsk(t *testing.T, in []byte) string {
	t.Helper()
	qkSrv.Lock()
	defer qkSrv.Unlock()
	if qkSrv.failed != "" {
		t.Fatal(qkSrv.failed)
	}
	if qkSrv.cmd == nil {
		dir, err := packageTempDir("mkqkfz")
		if err != nil {
			t.Fatal(err)
		}
		stdDir := copyStd(t, dir, map[string]string{qkShimPath: qkShim})
		if err := os.WriteFile(filepath.Join(dir, "main.mk"), []byte(qkServe), 0o644); err != nil {
			t.Fatal(err)
		}
		exe := filepath.Join(dir, "qkfz")
		if runtime.GOOS == "windows" {
			exe += ".exe"
		}
		t.Setenv("MK_CACHE", filepath.Join(dir, "cache"))
		out, status := mkCmd(t, dir, stdDir, "build", "--release", "-o", exe, "main.mk")
		if status != 0 {
			if strings.Contains(out, "no usable LLVM") {
				t.Skipf("needs the LLVM toolchain: %s", out)
			}
			qkSrv.failed = fmt.Sprintf("mk build: exit %d\n%s", status, out)
			t.Fatal(qkSrv.failed)
		}
		cmd := exec.Command(exe)
		stdin, err := cmd.StdinPipe()
		if err != nil {
			t.Fatal(err)
		}
		stdout, err := cmd.StdoutPipe()
		if err != nil {
			t.Fatal(err)
		}
		var eb bytes.Buffer
		cmd.Stderr = &eb
		if err := cmd.Start(); err != nil {
			t.Fatal(err)
		}
		qkSrv.cmd, qkSrv.in, qkSrv.out, qkSrv.err = cmd, stdin, bufio.NewReader(stdout), &eb
	}
	if _, err := fmt.Fprintf(qkSrv.in, "%d\n%s", len(in), in); err != nil {
		msg := qkSrv.err.String()
		qkSrv.cmd = nil
		t.Fatalf("driver gone on input %x: %v\n%s", in, err, msg)
	}
	line, err := qkSrv.out.ReadString('\n')
	if err != nil {
		msg := qkSrv.err.String()
		qkSrv.cmd = nil
		t.Fatalf("driver died on input %x: %v\n%s", in, err, msg)
	}
	return strings.TrimRight(line, "\r\n")
}

func qkStop() {
	qkSrv.Lock()
	defer qkSrv.Unlock()
	if qkSrv.cmd == nil {
		return
	}
	qkSrv.in.Close()
	_ = qkSrv.cmd.Wait()
	qkSrv.cmd = nil
}

func FuzzStdQuic_Ack(f *testing.F) {
	f.Cleanup(qkStop)
	f.Add([]byte{0, 2, 0, 0, 1, 2, 32})
	f.Add([]byte{2, 2, 50, 2, 2, 50, 3, 2, 1, 0, 0, 0, 0, 4, 5, 2})
	f.Add([]byte{3, 2, 255, 6, 10, 3, 2, 1, 0, 0, 0, 1})
	f.Add([]byte{0, 2, 0, 10, 0, 2, 0, 5, 1, 2, 4, 1, 2, 255})
	f.Fuzz(func(t *testing.T, in []byte) {
		if len(in) > 4096 {
			in = in[:4096]
		}
		if got := qkAsk(t, in); got != "ok" {
			t.Fatalf("input %x: driver answered %q", in, got)
		}
	})
}
