// Why: std.proc's test blocks start child processes and must each run in a
// process of their own, under a watchdog, on both I/O backends.
// What: TestProc_SpawnBlocks, TestProc_SpawnLinuxBlocks and TestProc_SpawnBlockNames, the
// runner of std/proc's tests_*.mk blocks (proc3Rewrite, proc3Blocks).
// How: each block is rewritten, in a copy of std, into an exported function of
// std.proc; one executable holds them all and runs one block per process.
// Its tests are cancel-safety tests; tools/gate/safety.go lists each.

package std

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

// The runner: every test block of std/proc's tests_spawn.mk, tests_lend.mk,
// tests_handles.mk, tests_cookbook.mk and tests_edges.mk (proc.Spawn, Child,
// Pipe, Pty and the cookbook's process recipes) and of tests_sim.mk (the same
// calls under a Sim) is rewritten, in a copy of std, into an exported function
// of std.proc, and one executable holds them all. Each block runs in its own
// process (its index the first argument, as std-proc_runblocks_test.go's runner does), under a
// watchdog, at dev and release, with MK_CARRIERS 1 and 16. A block's children
// are this same executable run again with a mode after the index.
//
// TestProc_SpawnLinuxBlocks starts wsl.exe, so it runs only with MK_LINUX=1, under
// tools/wsl-lock.ps1, with go test -p 1; on Linux each block runs on io_uring
// (MK_IO=auto) and on epoll, which must agree.

// proc3Files are the files whose blocks this runner runs.
var proc3Files = []string{"proc/tests_spawn.mk", "proc/tests_lend.mk", "proc/tests_handles.mk", "proc/tests_cookbook.mk", "proc/tests_edges.mk", "proc/tests_sim.mk"}

// proc3Rewrite returns the fixtures (the rewritten files and the probe)
// and the blocks in file order.
func proc3Rewrite(t *testing.T) (map[string]string, []proc2Block) {
	t.Helper()
	fixtures := map[string]string{}
	var blocks []proc2Block
	for _, f := range proc3Files {
		b, err := os.ReadFile(filepath.FromSlash(f))
		if err != nil {
			t.Fatal(err)
		}
		lines := strings.Split(strings.ReplaceAll(string(b), "\r\n", "\n"), "\n")
		for i, line := range lines {
			m := proc2Header.FindStringSubmatch(line)
			if m == nil {
				continue
			}
			fn := fmt.Sprintf("ZzP3Test%d", len(blocks))
			lines[i] = "export " + fn + "(sys: &System) {"
			blocks = append(blocks, proc2Block{name: m[1], fn: fn})
		}
		fixtures[f] = strings.Join(lines, "\n")
	}
	var p strings.Builder
	p.WriteString("// Generated by std/std-proc_spawnblocks_test.go.\n\n")
	p.WriteString("export ZzP3Run(sys: &System, i: int): bool {\n")
	for i, b := range blocks {
		fmt.Fprintf(&p, "    if i == %d {\n        %s(sys)\n        return true\n    }\n", i, b.fn)
	}
	p.WriteString("    return false\n}\n")
	fixtures["proc/zzp3probe.mk"] = p.String()
	return fixtures, blocks
}

const proc3Main = `import std.proc

export Main(sys: &System): int {
    if sys.args.Len() < 2 {
        return 2
    }
    var n := 0
    for b in sys.args[1].AsBytes() {
        n = n * 10 + int(b) - 48
    }
    if !proc.ZzP3Run(sys, n) {
        return 2
    }
    return 0
}
`

// proc3Base is the std to copy: MK_PROC3_BASE/std, or the tree's.
// MK_PROC3_BASE names a scratch std that compiles, for when files outside
// std/proc are mid-edit; std/proc itself always comes from the tree.
func proc3Base() string {
	if b := os.Getenv("MK_PROC3_BASE"); b != "" {
		return filepath.Join(b, "std")
	}
	return "."
}

// proc3Build builds the runner over a copy of the base std with this
// tree's std/proc over it.
func proc3Build(t *testing.T, linux bool, flags ...string) (string, []proc2Block) {
	t.Helper()
	fixtures, blocks := proc3Rewrite(t)
	if len(blocks) == 0 {
		t.Fatal("no test blocks found")
	}
	base := proc3Base()
	if base != "." {
		ents, err := os.ReadDir("proc")
		if err != nil {
			t.Fatal(err)
		}
		for _, e := range ents {
			k := "proc/" + e.Name()
			if _, ok := fixtures[k]; !ok && strings.HasSuffix(k, ".mk") {
				b, err := os.ReadFile(filepath.FromSlash(k))
				if err != nil {
					t.Fatal(err)
				}
				fixtures[k] = string(b)
			}
		}
	}
	root := t.TempDir()
	stdDir := proc2CopyStd(t, root, base, fixtures)
	if err := os.WriteFile(filepath.Join(root, "main.mk"), []byte(proc3Main), 0o644); err != nil {
		t.Fatal(err)
	}
	exe := filepath.Join(root, "main")
	if linux {
		flags = append(flags, "--target", "x86_64-linux")
	} else if runtime.GOOS == "windows" {
		exe += ".exe"
	}
	args := append([]string{"build"}, flags...)
	args = append(args, "-o", exe, "main.mk")
	out, status := mkCmd(t, root, stdDir, args...)
	if status != 0 {
		if strings.Contains(out, "no usable LLVM") {
			t.Skipf("needs the LLVM toolchain: %s", out)
		}
		t.Fatalf("mk build: exit %d\n%s", status, out)
	}
	return exe, blocks
}

// proc3Select is the indexes of the blocks whose names hold only (every
// block for an empty only), or an error when it matches none.
func proc3Select(blocks []proc2Block, only string) ([]int, error) {
	var idx []int
	for i, b := range blocks {
		if only == "" || strings.Contains(b.name, only) {
			idx = append(idx, i)
		}
	}
	if len(idx) == 0 {
		return nil, fmt.Errorf("MK_PROC3_ONLY=%q matches no block of %d", only, len(blocks))
	}
	return idx, nil
}

// proc3Blocks builds the runner (dev and release) and runs each block
// (MK_PROC3_ONLY: a substring of the names to run) with 1 and 16 carriers
// on host h, and on Linux once per backend.
func proc3Blocks(t *testing.T, h ioHost) {
	// A filter that matches no block fails before anything is built, so a
	// green run always ran blocks.
	_, all := proc3Rewrite(t)
	if _, err := proc3Select(all, os.Getenv("MK_PROC3_ONLY")); err != nil {
		t.Fatal(err)
	}
	backends := []string{""}
	if h.linux {
		backends = []string{"MK_IO=auto", "MK_IO=epoll"}
	}
	for _, mode := range []string{"dev", "release"} {
		t.Run(mode, func(t *testing.T) {
			var flags []string
			if mode == "release" {
				flags = append(flags, "--release")
			}
			exe, blocks := proc3Build(t, h.linux, flags...)
			idx, err := proc3Select(blocks, os.Getenv("MK_PROC3_ONLY"))
			if err != nil {
				t.Fatal(err)
			}
			type variant struct {
				carriers int
				backend  string
			}
			var vs []variant
			for _, be := range backends {
				for _, n := range []int{1, 16} {
					vs = append(vs, variant{n, be})
				}
			}
			var calls []ioCall
			for _, v := range vs {
				for _, i := range idx {
					env := []string{fmt.Sprintf("MK_CARRIERS=%d", v.carriers)}
					// MK_PROC3_BLOCKED also runs the blocks whose fix lies
					// outside std/proc (SpRunBlocked in tests_spawn.mk).
					if os.Getenv("MK_PROC3_BLOCKED") != "" {
						env = append(env, "MK_PROC3_BLOCKED=1")
					}
					if v.backend != "" {
						env = append(env, v.backend)
					}
					calls = append(calls, ioCall{env: env, watch: 120, args: []string{fmt.Sprint(i)}})
				}
			}
			runs := h.runMany(t, exe, calls)
			for k, r := range runs {
				b := blocks[idx[k%len(idx)]]
				v := vs[k/len(idx)]
				name := fmt.Sprintf("%s/carriers=%d", b.name, v.carriers)
				if v.backend != "" {
					name += "/" + strings.TrimPrefix(v.backend, "MK_IO=")
				}
				t.Run(name, func(t *testing.T) {
					if r.code == 124 {
						t.Fatalf("no exit within %d s\nstdout: %s\nstderr: %s", calls[k].watch, stdioTail(r.stdout), stdioTail(r.stderr))
					}
					if r.code != 0 {
						t.Fatalf("exit %d\nstdout: %s\nstderr: %s", r.code, stdioTail(r.stdout), stdioTail(r.stderr))
					}
				})
			}
			// On Windows the refusals block names its Unix-domain listener
			// relative to the working directory, so a TEMP past sun_path
			// (unixLongTemp), which it inherits, cannot reach the address.
			if h.linux || runtime.GOOS != "windows" {
				return
			}
			for _, i := range idx {
				if !strings.HasPrefix(blocks[i].name, "Command.handles: Spawn refuses") {
					continue
				}
				t.Run(blocks[i].name+"/long TEMP", func(t *testing.T) {
					long := unixLongTemp(t)
					r := runNativeEnv(t, exe, ioCall{env: []string{"MK_CARRIERS=1", "TEMP=" + long, "TMP=" + long}, watch: 120, args: []string{fmt.Sprint(i)}})
					if r.code != 0 {
						t.Fatalf("exit %d\nstdout: %s\nstderr: %s", r.code, stdioTail(r.stdout), stdioTail(r.stderr))
					}
				})
			}
		})
	}
}

// TestProc_SpawnBlocks runs std/proc's blocks on the host.
func TestProc_SpawnBlocks(t *testing.T) { proc3Blocks(t, hostIo) }

// TestProc_SpawnLinuxBlocks runs them as x86_64-linux programs under WSL.
func TestProc_SpawnLinuxBlocks(t *testing.T) {
	linuxGate(t)
	stdioNeedWSL(t)
	proc3Blocks(t, linuxIo)
}

// TestProc_SpawnBlockNames: every block has a function and a name of its own
// (the runner names subtests by block name and MK_PROC3_ONLY selects by it).
func TestProc_SpawnBlockNames(t *testing.T) {
	_, blocks := proc3Rewrite(t)
	if len(blocks) == 0 {
		t.Fatal("no blocks")
	}
	seen := map[string]bool{}
	for _, b := range blocks {
		if seen[b.name] {
			t.Errorf("two blocks are named %q", b.name)
		}
		seen[b.name] = true
	}
}
