// Why: QUIC endpoint datagram dispatch, Retry token verification, stateless
// reset formatting, closing/draining rate limiting, and CID demuxing operate on
// untrusted peer datagrams; no byte sequence may panic, hang, overflow arithmetic,
// or leak slots or memory.
//
// What: FuzzStdQuic_Endpoint, driven by a release binary built over a copy of
// std with a fixture shim inside std.quic.
//
// How: streams "<length>\n" + bytes over stdin to QuicEndFuzzMain; the shim
// dispatches datagrams against a live sim-backed Endpoint (draining/abandoning
// any queued connections so slots never leak), plus exercises VerifyRetryToken,
// WriteStatelessReset, ResetLimiter, CloseState, and DemuxTable.
// Its fuzz target reads untrusted input; tools/gate/safety.go lists each untrusted-input target.

