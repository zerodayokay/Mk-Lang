// Why: the HTTP/3 varint, frame header, SETTINGS, control-stream and
// request-stream parsers read untrusted peer bytes; no input may panic,
// violate slice bounds, leak heap memory, or break RFC 9114 invariants.
//
// What: FuzzStdHttpH3_Frames, with its driver hh3Serve and fixture hh3Shim.
//
// How: std.http.h3 is std-only, so a fixture file of std.http in a copy of
// std (hh3Shim) holds the driver's body, and a program calls it. One
// long-running release driver answers every input of a fuzz worker ("<len>\n"
// then bytes; answer lines then END). Each input feeds varint/frame/settings
// codecs plus live Session.Poll and Exchange.RequestHead/Read over
// std.net.pipe's MuxPair; any broken invariant panics.
//
// Its fuzz targets read untrusted input; tools/gate/safety.go lists each untrusted-input target.

package std

