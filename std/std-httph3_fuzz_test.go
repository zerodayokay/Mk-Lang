const hh3ShimPath = "http/zz_h3fuzz_shim.mk"

const hh3Shim = `// Generated by std/std-httph3_fuzz_test.go: a fixture of its std copy.
//
// Why: std.http.h3 is std-only, so its fuzz driver reaches it through a
// fixture file of std.http.
// What: H3FuzzMain, which answers fuzz inputs on standard input.
// How: byte 0 selects mode (codec/settings vs live control/request streams
// over MuxPair); remaining bytes drive the selected parser totals without
// panics or memory leaks.

import hf = std.http.fields
import std.http.h3
import std.net.pipe

Hh3RoundTripFrame(a: &Arena, fh: h3.FrameHeader, payload: []u8): OutOfMemory!void {
    out := try a.Slice[u8](payload.Len() + 32)
    if fh.kind == h3.FrameGoaway || fh.kind == h3.FrameCancelPush || fh.kind == h3.FrameMaxPushId {
        match h3.ParseSingleIdPayload(payload) {
            ok(id) {
                n := h3.WriteSingleIdFrame(out, fh.kind, id)
                Assert(n > 0)
                back := h3.ParseFrameHeader(out[0..n]).Must()
                Assert(back.kind == fh.kind)
                bid := h3.ParseSingleIdPayload(out[back.header_len..n]).Must()
                Assert(bid == id)
            }
            err(_) {}
        }
    } else if fh.kind == h3.FrameSettings {
        var st := h3.InitialSettings
        match st.Apply(a.Alloc(), payload) {
            ok(_) {
                n := h3.EncodeSettings(out, st.max_field_section_size, st.qpack_max_table_capacity, st.qpack_blocked_streams, false)
                Assert(n > 0)
                back := h3.ParseFrameHeader(out[0..n]).Must()
                Assert(back.kind == h3.FrameSettings)
                var st2 := h3.InitialSettings
                _ = st2.Apply(a.Alloc(), out[back.header_len..n]).Must()
            }
            err(_) {}
        }
    }
}

Hh3RunCodec(a: &Arena, w: mut Writer, input: []u8): WriteError|OutOfMemory!void {
    var at := 0
    for at < input.Len() {
        fh := h3.ParseFrameHeader(input[at..]) else {
            try w.Str("tail\n")
            return
        }
        rem := input.Len() - at - fh.header_len
        if fh.length > Cast[u64](rem) {
            try w.Str("trunc\n")
            return
        }
        plen := Cast[int](fh.length)
        payload := input[at + fh.header_len..at + fh.header_len + plen]
        try Hh3RoundTripFrame(a, fh, payload)
        try Print(w, "ok frame {kind}\n", (kind: fh.kind))
        at += fh.header_len + plen
    }
}

Hh3RunSession(sys: &System, w: mut Writer, mode: u8, input: []u8): WriteError|OutOfMemory!void {
    (client: cm, server: sm) := try pipe.MuxPair(sys.heap, 4096)
    defer cm.Abandon()
    defer sm.Abandon()
    ss := h3.Session.Server(sys.heap, sys.io, &sm, 4096) else {
        try w.Str("err init\n")
        return
    }
    defer ss.Free(sys.heap.Alloc())

    if (mode & 1) == 0 {
        u := (cm.Open(sys.io, true, true) else {
            try w.Str("err open\n")
            return
        }).Must()
        defer cm.Release(u)
        _ = cm.Write(sys.io, &u, input, (mode & 2) != 0) else {
        }
        ss.Ref().Poll(sys.io) else e {
            match e {
                h3.Violation(code, stream: _) { try Print(w, "err {code}\n", (code: code)) }
                _ { try w.Str("err other\n") }
            }
            return
        }
        try w.Str("ok ctrl\n")
        return
    }

    b := (cm.Open(sys.io, false, true) else {
        try w.Str("err open\n")
        return
    }).Must()
    defer cm.Release(b)
    _ = cm.Write(sys.io, &b, input, true) else {
    }
    ex := h3.Exchange.Accept(ss.Ref(), sys.io) else e {
        match e {
            h3.Violation(code, stream: _) { try Print(w, "err {code}\n", (code: code)) }
            _ { try w.Str("err accept\n") }
        }
        return
    }
    defer ex.Release(ss.Ref())
    var fb := hf.FieldBlock.New(sys.heap.Alloc())
    defer fb.Free(sys.heap.Alloc())
    ex.RequestHead(sys.io, mut fb) else e {
        match e {
            h3.Violation(code, stream: _) { try Print(w, "err {code}\n", (code: code)) }
            h3.TooLarge { try w.Str("err toolarge\n") }
            _ { try w.Str("err head\n") }
        }
        return
    }
    var rbuf: [256]u8 = [0; 256]
    for {
        n := ex.Read(sys.io, mut rbuf[..]) else e {
            match e {
                h3.Violation(code, stream: _) { try Print(w, "err {code}\n", (code: code)) }
                _ { try w.Str("err read\n") }
            }
            return
        }
        if n == 0 {
            break
        }
    }
    try w.Str("ok req\n")
}

/// Serves HTTP/3 frame and session fuzz inputs on standard input until EOF.
export H3FuzzMain(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {
    var inp := sys.Stdin()
    var out := sys.Stdout()
    data := try sys.arena.Slice[u8](1 << 16)
    var head: [32]u8 = [0; 32]
    for {
        k := try inp.Until(0x0A, mut head[..])
        if k == 0 {
            return
        }
        line := try str.From(head[0..k - 1])
        n := Cast[int](try line.ParseInt())
        got := try inp.ReadAll(mut data[0..n])
        var ar := try Arena.New(sys.heap)
        defer ar.Free()
        if got < 1 {
            try out.Str("short\n")
        } else if (data[0] & 4) == 0 {
            try Hh3RunCodec(&ar, mut out, data[1..got])
        } else {
            try Hh3RunSession(sys, mut out, data[0], data[1..got])
        }
        try out.Str("END\n")
        try out.Flush()
    }
}
`

const hh3Serve = "import std.http\n\nexport Main(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {\n    try http.H3FuzzMain(sys)\n}\n"

var hh3Srv struct {
	sync.Mutex
	cmd    *exec.Cmd
	in     io.WriteCloser
	out    *bufio.Reader
	err    *bytes.Buffer
	failed string
}

func hh3Ask(t *testing.T, in []byte) []string {
	t.Helper()
	hh3Srv.Lock()
	defer hh3Srv.Unlock()
	if hh3Srv.failed != "" {
		t.Fatal(hh3Srv.failed)
	}
	if hh3Srv.cmd == nil {
		dir, err := packageTempDir("mkhh3z")
		if err != nil {
			t.Fatal(err)
		}
		stdDir := copyStd(t, dir, map[string]string{hh3ShimPath: hh3Shim})
		if err := os.WriteFile(filepath.Join(dir, "main.mk"), []byte(hh3Serve), 0o644); err != nil {
			t.Fatal(err)
		}
		exe := filepath.Join(dir, "hh3z")
		if runtime.GOOS == "windows" {
			exe += ".exe"
		}
		t.Setenv("MK_CACHE", filepath.Join(dir, "cache"))
		out, status := mkCmd(t, dir, stdDir, "build", "--release", "-o", exe, "main.mk")
		if status != 0 {
			if strings.Contains(out, "no usable LLVM") {
				t.Skipf("needs the LLVM toolchain: %s", out)
			}
			hh3Srv.failed = fmt.Sprintf("mk build: exit %d\n%s", status, out)
			t.Fatal(hh3Srv.failed)
		}
		cmd := exec.Command(exe)
		stdin, err := cmd.StdinPipe()
		if err != nil {
			t.Fatal(err)
		}
		stdout, err := cmd.StdoutPipe()
		if err != nil {
			t.Fatal(err)
		}
		var eb bytes.Buffer
		cmd.Stderr = &eb
		if err := cmd.Start(); err != nil {
			t.Fatal(err)
		}
		hh3Srv.cmd, hh3Srv.in, hh3Srv.out, hh3Srv.err = cmd, stdin, bufio.NewReader(stdout), &eb
	}
	if _, err := fmt.Fprintf(hh3Srv.in, "%d\n%s", len(in), in); err != nil {
		hh3Died(t, in, err)
	}
	var lines []string
	for {
		line, err := hh3Srv.out.ReadString('\n')
		if err != nil {
			hh3Died(t, in, err)
		}
		line = strings.TrimRight(line, "\r\n")
		if line == "END" {
			return lines
		}
		lines = append(lines, line)
	}
}

func hh3Died(t *testing.T, in []byte, err error) {
	t.Helper()
	msg := hh3Srv.err.String()
	hh3Srv.cmd = nil
	t.Fatalf("driver gone on input %x: %v\n%s", in, err, msg)
}

func hh3Stop() {
	hh3Srv.Lock()
	defer hh3Srv.Unlock()
	if hh3Srv.cmd == nil {
		return
	}
	hh3Srv.in.Close()
	_ = hh3Srv.cmd.Wait()
	hh3Srv.cmd = nil
}

func hh3Unhex(s string) []byte {
	b, err := hex.DecodeString(strings.ReplaceAll(s, " ", ""))
	if err != nil {
		panic(err)
	}
	return b
}

var hh3Seeds = []string{
	"00 04 02 06 20",                    // codec: SETTINGS MAX_FIELD_SECTION_SIZE=32
	"00 04 04 06 0a 06 14",              // codec: duplicate setting
	"00 07 01 04",                       // codec: GOAWAY 4
	"00 03 01 02",                       // codec: CANCEL_PUSH 2
	"00 0d 01 08",                       // codec: MAX_PUSH_ID 8
	"00 21 03 616263",                   // codec: GREASE frame
	"04 00 04 02 06 20",                 // session ctrl: 0x00 + SETTINGS
	"06 00 04 00",                       // session ctrl + FIN: H3_CLOSED_CRITICAL_STREAM
	"04 00 07 01 00",                    // session ctrl: GOAWAY first -> H3_MISSING_SETTINGS
	"04 02 20",                          // session ctrl: QPACK enc SetCap(0)
	"05 01 09 0000 d1 d7 c1 50 02 6578", // session req: valid GET https / ex
	"05 01 09 0000 d1 d7 c1 50 02 6578 00 02 6869", // session req: GET + DATA
	"05 02 00", // session req: H2 PRIORITY -> H3_FRAME_UNEXPECTED
}

func FuzzStdHttpH3_Frames(f *testing.F) {
	f.Cleanup(hh3Stop)
	for _, s := range hh3Seeds {
		f.Add(hh3Unhex(s))
	}
	f.Fuzz(func(t *testing.T, in []byte) {
		if len(in) > 32768 {
			in = in[:32768]
		}
		for _, l := range hh3Ask(t, in) {
			if l != "short" && l != "tail" && l != "trunc" && !strings.HasPrefix(l, "ok ") && !strings.HasPrefix(l, "err ") {
				t.Fatalf("input %x: answer %q", in, l)
			}
		}
	})
}
