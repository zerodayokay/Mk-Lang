// Why: QUIC packet headers, frames and transport parameters are parsed from
// untrusted peer datagrams; no input may panic, hang, overflow arithmetic or
// break encode/decode round-trip invariants.
//
// What: FuzzStdQuic_Packets, FuzzStdQuic_Frames and FuzzStdQuic_Params,
// driven by a long-running release binary built over a copy of std with a
// fixture shim inside std.quic.
//
// How: each fuzz worker feeds "<mode> <length>\n" + bytes to QuicFuzzMain
// over stdin/stdout; the shim parses packets (including coalesced chains),
// iterates frames and checks WriteFrame, and decodes/re-encodes transport
// parameters. A panic or protocol error kills the driver and fails the run.
// Its fuzz targets read untrusted input; tools/gate/safety.go lists each untrusted-input target.

package std

