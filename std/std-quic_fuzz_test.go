const qzShimPath = "quic/zz_quicfuzz_shim.mk"

const qzShim = `// Generated by std/std-quic_fuzz_test.go: a fixture of its std copy.
//
// Why: std.quic's wire parsers are module-private, so the fuzz driver lives
// inside std.quic.
// What: QuicFuzzMain, answering mode p (packets), f (frames) and t (params).
// How: reads "<mode> <length>\n" then length bytes from stdin, runs the
// bounded parser + round-trip checks, and prints "ok\n", "err\n" or "none\n".

FuzzPackets(data: []u8): str {
    if data.Len() == 0 {
        return "none"
    }
    short_cid_len := int(data[0] % 21)
    var pos := 1
    var steps := 0
    for pos < data.Len() && steps < 32 {
        steps += 1
        p := ParsePacket(data[pos..data.Len()], short_cid_len) else {
            return "none"
        }
        match p {
            .Long(hdr, packet) {
                if packet.Len() == 0 {
                    Panic("empty long packet slice")
                }
                _ = hdr.kind
                pos += packet.Len()
            }
            .Short(hdr, packet) {
                _ = hdr.pn_offset
                _ = packet.Len()
                return "ok"
            }
            .Retry(version, dcid, scid, token, tag, packet) {
                _ = version
                _ = dcid
                _ = scid
                _ = token
                _ = tag
                odcid := CidFromSlice(b"\x83\x94\xc8\xf0\x3e\x51\x57\x08")
                _ = RetryTag(&odcid, packet)
                return "ok"
            }
            .VersionNeg(dcid, scid, versions) {
                _ = dcid
                _ = scid
                _ = versions
                return "ok"
            }
            .UnknownVersion(hdr) {
                var vn: [600]u8 = [0; 600]
                vers: [1]u32 = [Version1]
                _ = WriteVersionNeg(mut vn[..], 0x40, hdr.scid, hdr.dcid, vers[..])
                return "ok"
            }
        }
    }
    return "ok"
}

FuzzFrames(data: []u8): str {
    if data.Len() == 0 {
        return "err"
    }
    client := (data[0] & 1) == 0
    payload := data[1..data.Len()]
    var ranges: [256]AckRange = [AckRange(lo: 0, hi: 0); 256]
    var it := FrameIter.New(payload, client)
    var scratch: [4096]u8 = [0; 4096]
    for {
        f := it.Next(mut ranges[..]) else {
            return "err"
        }
        match f {
            none { return "ok" }
            some(frame) {
                if wn := WriteFrame(mut scratch[..], &frame, ranges[..]) {
                    var r2: [256]AckRange = [AckRange(lo: 0, hi: 0); 256]
                    var it2 := FrameIter.New(scratch[0..wn], client)
                    _ = it2.Next(mut r2[..]).Must().Must()
                }
            }
        }
    }
    return "ok"
}

FuzzParams(data: []u8): str {
    if data.Len() == 0 {
        return "err"
    }
    from_client := (data[0] & 1) == 0
    raw := data[1..data.Len()]
    p := DecodeParams(raw, from_client) else {
        return "err"
    }
    var out: [4096]u8 = [0; 4096]
    n := EncodeParams(mut out[..], &p)
    if n > 0 {
        _ = DecodeParams(out[0..n], from_client).Must()
    }
    return "ok"
}

/// Serves fuzz inputs on standard input until EOF.
export QuicFuzzMain(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {
    var inp := sys.Stdin()
    var out := sys.Stdout()
    data := try sys.arena.Slice[u8](1 << 16)
    var head: [32]u8 = [0; 32]
    for {
        k := try inp.Until(0x0A, mut head[..])
        if k == 0 {
            return
        }
        line := try str.From(head[0..k - 1])
        (before: mode, after: len_s) := line.SplitOnce(" ").Must()
        n := Cast[int](try len_s.ParseInt())
        got := try inp.ReadAll(mut data[0..n])
        var ans := "err"
        if mode == "p" {
            ans = FuzzPackets(data[0..got])
        } else if mode == "f" {
            ans = FuzzFrames(data[0..got])
        } else {
            ans = FuzzParams(data[0..got])
        }
        try out.Str(ans)
        try out.Str("\n")
        try out.Flush()
    }
}
`

const qzServe = "import std.quic\n\nexport Main(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {\n    try quic.QuicFuzzMain(sys)\n}\n"

var qzSrv struct {
	sync.Mutex
	cmd    *exec.Cmd
	in     io.WriteCloser
	out    *bufio.Reader
	err    *bytes.Buffer
	failed string
}

func qzAsk(t *testing.T, mode byte, in []byte) string {
	t.Helper()
	qzSrv.Lock()
	defer qzSrv.Unlock()
	if qzSrv.failed != "" {
		t.Fatal(qzSrv.failed)
	}
	if qzSrv.cmd == nil {
		dir, err := packageTempDir("mkquicfz")
		if err != nil {
			t.Fatal(err)
		}
		stdDir := copyStd(t, dir, map[string]string{qzShimPath: qzShim})
		if err := os.WriteFile(filepath.Join(dir, "main.mk"), []byte(qzServe), 0o644); err != nil {
			t.Fatal(err)
		}
		exe := filepath.Join(dir, "qfz")
		if runtime.GOOS == "windows" {
			exe += ".exe"
		}
		t.Setenv("MK_CACHE", filepath.Join(dir, "cache"))
		out, status := mkCmd(t, dir, stdDir, "build", "--release", "-o", exe, "main.mk")
		if status != 0 {
			if strings.Contains(out, "no usable LLVM") {
				t.Skipf("needs the LLVM toolchain: %s", out)
			}
			qzSrv.failed = fmt.Sprintf("mk build: exit %d\n%s", status, out)
			t.Fatal(qzSrv.failed)
		}
		cmd := exec.Command(exe)
		stdin, err := cmd.StdinPipe()
		if err != nil {
			t.Fatal(err)
		}
		stdout, err := cmd.StdoutPipe()
		if err != nil {
			t.Fatal(err)
		}
		var eb bytes.Buffer
		cmd.Stderr = &eb
		if err := cmd.Start(); err != nil {
			t.Fatal(err)
		}
		qzSrv.cmd, qzSrv.in, qzSrv.out, qzSrv.err = cmd, stdin, bufio.NewReader(stdout), &eb
	}
	if _, err := fmt.Fprintf(qzSrv.in, "%c %d\n%s", mode, len(in), in); err != nil {
		qzDied(t, in, err)
	}
	line, err := qzSrv.out.ReadString('\n')
	if err != nil {
		qzDied(t, in, err)
	}
	return strings.TrimRight(line, "\r\n")
}

func qzDied(t *testing.T, in []byte, err error) {
	t.Helper()
	msg := qzSrv.err.String()
	qzSrv.cmd = nil
	t.Fatalf("driver gone on input %x: %v\n%s", in, err, msg)
}

func qzStop() {
	qzSrv.Lock()
	defer qzSrv.Unlock()
	if qzSrv.cmd == nil {
		return
	}
	qzSrv.in.Close()
	_ = qzSrv.cmd.Wait()
	qzSrv.cmd = nil
}

func qzUnhex(s string) []byte {
	b, err := hex.DecodeString(strings.ReplaceAll(s, " ", ""))
	if err != nil {
		panic(err)
	}
	return b
}

func FuzzStdQuic_Packets(f *testing.F) {
	f.Cleanup(qzStop)
	// RFC 9001 A.3 Server Initial, A.4 Retry, A.5 Short Header, Version Negotiation, short packets.
	f.Add(append([]byte{8}, qzUnhex("cf000000010008f067a5502a4262b5004075c0d95a482cd0991cd25b0aac406a5816b6394100f37a1c69797554780bb38cc5a99f5ede4cf73c3ec2493a1839b3dbcba3f6ea46c5b7684df3548e7ddeb9c3bf9c73cc3f3bded74b562bfb19fb84022f8ef4cdd93795d77d06edbb7aaf2f58891850abbdca3d20398c276456cbc42158407dd074ee")...))
	f.Add(append([]byte{8}, qzUnhex("ff000000010008f067a5502a4262b5746f6b656e04a265ba2eff4d829058fb3f0f2496ba")...))
	f.Add(append([]byte{0}, qzUnhex("4cfe4189655e5cd55c41f69080575d7999c25a5bfb")...))
	f.Add([]byte{8, 0x80, 0, 0, 0, 0, 2, 1, 2, 2, 3, 4, 0, 0, 0, 1})
	f.Add([]byte{8, 0x00, 1, 2, 3, 4})
	f.Add([]byte{0, 0x40, 1, 2, 3})
	f.Fuzz(func(t *testing.T, in []byte) {
		if len(in) > 4096 {
			in = in[:4096]
		}
		got := qzAsk(t, 'p', in)
		if got != "ok" && got != "none" {
			t.Fatalf("packets %x: %q", in, got)
		}
	})
}

