// Why: the HPACK decoder and the Huffman decoder read a peer's bytes; no
// input may panic, hang, pass the list budget, or decode to something the
// encoder does not give back.
// What: FuzzStdHttpFields_Hpack and FuzzStdHttpFields_Huffman, with their
// driver hfServe and its fixture hfShim.
// How: std.http.fields is std-only, so a fixture file of std.http in a
// copy of std (hfShim) holds the driver's body, and a program calls it.
// One long-running release driver answers every input of a fuzz worker
// ("<mode> <length>\n" then the bytes; the answer lines, then END). Mode h
// decodes up to three blocks under fuzzed table and list sizes, into a
// copying sink and into a FieldBlock, and has the driver check that the two
// agree, the list budget, and a re-encoding round trip itself; mode u
// decodes one Huffman string, compared here with hfHuffDecodeRef, and its
// re-encoding with hfHuffEncodeRef.
//
//	go test ./std -run '^$' -fuzz FuzzStdHttpFields_Hpack -fuzztime 5m -parallel 2 -fuzzminimizetime 100x
//
// Each execution is a round trip to the driver, so go test's default
// minimisation (60 s a new input) would take most of a run on a cold fuzz
// cache; the gate passes -fuzzminimizetime 100x for both targets.
//
// Its fuzz targets read untrusted input; tools/gate/safety.go lists each untrusted-input target.

