// hfShim is the driver's body, a fixture of std.http.
const hfShim = `// Generated by std/std-httpfields_fuzz_test.go: a fixture of its std copy.
//
// Why: std.http.fields is std-only, so its fuzz driver reaches it through a
// fixture file of std.http.
// What: FieldsFuzzMain, which answers the fuzz inputs on standard input.
// How: each input is "<mode> <length>\n" then the bytes; mode h decodes
// up to three blocks under fuzzed limits, into a copying sink and into a
// FieldBlock, and re-encodes what decoded; mode u decodes the bytes as one
// Huffman string and encodes it again. A broken invariant panics, so the Go
// side sees the driver die.

import std.http.fields

// One field the copying sink kept: offsets into its bytes.
struct FzSpan {
    at: int
    name: int
    value: int
    never_index: bool
}

// A sink that copies every field, any bytes.
struct FzRaw {
    bytes: HeapList[u8]
    spans: HeapList[FzSpan]
}

impl fields.Sink for FzRaw {
    Add(mut self, a: &Alloc, name: []u8, value: []u8, never_index: bool, name_index: int): OutOfMemory!void {
        _ = name_index
        at := self.bytes.Len()
        try self.bytes.Extend(a, name)
        try self.bytes.Extend(a, value)
        try self.spans.Push(a, FzSpan(at: at, name: name.Len(), value: value.Len(), never_index: never_index))
    }
}

FzRaw.Free(self, a: &Alloc) {
    FzRaw(bytes, spans) := self
    bytes.Free(a)
    spans.Free(a)
}

// FzName and FzValue are field i of r.
FzName(r: &FzRaw, i: int): []u8 {
    s := r.spans[i]
    return r.bytes.Items()[s.at..s.at + s.name]
}

FzValue(r: &FzRaw, i: int): []u8 {
    s := r.spans[i]
    return r.bytes.Items()[s.at + s.name..s.at + s.name + s.value]
}

FzEq(x: []u8, y: []u8): bool {
    if x.Len() != y.Len() {
        return false
    }
    for i in 0..x.Len() {
        if x[i] != y[i] {
            return false
        }
    }
    return true
}

// FzSame is whether two copying sinks hold the same fields.
FzSame(a: &FzRaw, b: &FzRaw): bool {
    if a.spans.Len() != b.spans.Len() {
        return false
    }
    for i in 0..a.spans.Len() {
        if a.spans[i].never_index != b.spans[i].never_index || !FzEq(FzName(a, i), FzName(b, i)) || !FzEq(FzValue(a, i), FzValue(b, i)) {
            return false
        }
    }
    return true
}

// FzEncode encodes r's fields with enc into a buffer of a, by Start and
// Write, and returns it.
FzEncode(a: &Arena, enc: mut fields.Encoder, r: &FzRaw): OutOfMemory![]u8 from a {
    var need := enc.StartBound()
    for i in 0..r.spans.Len() {
        need += enc.FieldBound(FzName(r, i), FzValue(r, i))
    }
    out := try a.Slice[u8](need)
    var o := enc.Start(out) else {
        Panic("Start refused a buffer of StartBound bytes")
    }
    for i in 0..r.spans.Len() {
        mode := if r.spans[i].never_index { fields.Mode.Never } else { fields.Mode.Index }
        o += enc.Write(mut out[o..], FzName(r, i), FzValue(r, i), mode) else {
            Panic("Write refused a buffer of FieldBound bytes")
        }
    }
    return out[0..o]
}

FzHex(w: mut Writer, b: []u8): WriteError!void {
    digits := "0123456789abcdef".AsBytes()
    var two: [2]u8 = [0; 2]
    for c in b {
        two[0] = digits[int(c >> 4)]
        two[1] = digits[int(c & 15)]
        try w.Bytes(two[..])
    }
}

const FzSizes: [4]int = [4096, 256, 0, 64]
const FzLimits: [4]int = [1 << 16, 100, 0, 4096]

// FzHpack decodes in's blocks on one decoder into a copying sink and on a
// second one into a FieldBlock, which must agree; each list that fits is
// encoded again and decoded by a third pair, which must give it back.
FzHpack(a: &Arena, h: &Alloc, w: mut Writer, input: []u8): WriteError|OutOfMemory!void {
    if input.Len() < 3 {
        try w.Str("short\n")
        return
    }
    table := FzSizes[int(input[0] & 3)]
    limit := FzLimits[int((input[0] >> 2) & 3)]
    rest := input[3..]
    c1 := int(input[1]) % (rest.Len() + 1)
    c2 := c1 + int(input[2]) % (rest.Len() - c1 + 1)
    var dec := try fields.Decoder.New(h, table, limit)
    defer dec.Free(h)
    var decb := try fields.Decoder.New(h, table, limit)
    defer decb.Free(h)
    var enc := try fields.Encoder.New(h, table, true)
    defer enc.Free(h)
    var dec2 := try fields.Decoder.New(h, table, 1 << 20)
    defer dec2.Free(h)
    var fb := fields.FieldBlock.New(h)
    defer fb.Free(h)
    cuts := [0, c1, c2, rest.Len()]
    for k in 0..3 {
        blk := rest[cuts[k]..cuts[k + 1]]
        var raw := FzRaw(bytes: HeapList[u8].New(h), spans: HeapList[FzSpan].New(h))
        defer raw.Free(h)
        fb.Reset()
        var word := "ok"
        var more := true
        match dec.Decode(h, mut raw, blk) {
            ok(o) {
                if o == fields.Outcome.TooLarge {
                    word = "too large"
                }
            }
            err(e) {
                try Print(w, "err {e}\n", (e))
                word = "err"
                more = false
            }
        }
        // The FieldBlock's decoder must reach the same outcome.
        same := match decb.Decode(h, mut fb, blk) {
            ok(o) { word == (if o == fields.Outcome.TooLarge { "too large" } else { "ok" }) }
            err(_) { word == "err" }
        }
        if !same {
            Panic("the FieldBlock's decoder reached another outcome")
        }
        if raw.bytes.Len() + 32 * raw.spans.Len() > limit {
            Panic("the sink got more than the list budget")
        }
        if !FzBlockSame(&raw, &fb) {
            Panic("the FieldBlock holds other fields than the copying sink")
        }
        if decb.TableSize() != dec.TableSize() || decb.TableLen() != dec.TableLen() {
            Panic("two decoders of one input hold different tables")
        }
        if word == "ok" {
            try Print(w, "ok {n}\n", (n: raw.spans.Len()))
            out := try FzEncode(a, mut enc, &raw)
            var back := FzRaw(bytes: HeapList[u8].New(h), spans: HeapList[FzSpan].New(h))
            defer back.Free(h)
            o2 := dec2.Decode(h, mut back, out) else {
                Panic("the re-encoded block does not decode")
            }
            if o2 != fields.Outcome.Fits || !FzSame(&raw, &back) {
                Panic("the re-encoded block decodes to another list")
            }
            if dec2.TableSize() != enc.TableSize() || dec2.TableLen() != enc.TableLen() {
                Panic("the re-encoding pair's tables differ")
            }
        } else if word == "too large" {
            try w.Str("too large\n")
        }
        if !more {
            // A decoder that failed refuses every later block.
            var again := FzRaw(bytes: HeapList[u8].New(h), spans: HeapList[FzSpan].New(h))
            defer again.Free(h)
            match dec.Decode(h, mut again, rest[cuts[k + 1]..]) {
                ok(_) { Panic("a decoder took a block after it failed") }
                err(e2) { try Print(w, "again {e2}\n", (e2)) }
            }
            return
        }
    }
}

// FzUtf8 is whether b is UTF-8.
FzUtf8(b: []u8): bool {
    _ = str.From(b) else {
        return false
    }
    return true
}

// FzBlockSame is whether a FieldBlock holds exactly a copying sink's
// fields, with Text some exactly for those whose name and value are UTF-8.
FzBlockSame(r: &FzRaw, fb: &fields.FieldBlock): bool {
    if fb.Len() != r.spans.Len() {
        return false
    }
    for i in 0..fb.Len() {
        f := fb.Get(i)
        if f.sensitive != r.spans[i].never_index || !FzEq(f.name, FzName(r, i)) || !FzEq(f.value, FzValue(r, i)) {
            return false
        }
        if fb.Text(i).IsSome() != (FzUtf8(f.name) && FzUtf8(f.value)) {
            return false
        }
    }
    return true
}

// FzHuffman decodes input as one Huffman string (the value of :path),
// prints it, encodes it again and checks that it decodes back.
FzHuffman(a: &Arena, h: &Alloc, w: mut Writer, input: []u8): WriteError|OutOfMemory!void {
    blk := try a.Slice[u8](input.Len() + 8)
    blk[0] = 0x04
    var k := 2
    // The string's head: H set, the length on a 7-bit prefix.
    var n := input.Len()
    if n < 127 {
        blk[1] = Trunc[u8](0x80 | n)
    } else {
        blk[1] = 0xFF
        n -= 127
        for n >= 128 {
            blk[k] = Trunc[u8](n & 0x7F) | 0x80
            n = n >> 7
            k += 1
        }
        blk[k] = Trunc[u8](n)
        k += 1
    }
    (mut blk[k..k + input.Len()]).CopyFrom(input)
    var dec := try fields.Decoder.New(h, 0, 1 << 20)
    defer dec.Free(h)
    var raw := FzRaw(bytes: HeapList[u8].New(h), spans: HeapList[FzSpan].New(h))
    defer raw.Free(h)
    _ = dec.Decode(h, mut raw, blk[0..k + input.Len()]) else e {
        try Print(w, "err {e}\n", (e))
        return
    }
    if raw.spans.Len() != 1 {
        Panic("one field expected")
    }
    value := FzValue(&raw, 0)
    try w.Str("ok ")
    try FzHex(w, value)
    try w.Str("\n")
    var enc := try fields.Encoder.New(h, 0, true)
    defer enc.Free(h)
    out := try a.Slice[u8](enc.FieldBound(":path".AsBytes(), value))
    m := enc.Write(out, ":path".AsBytes(), value, fields.Mode.NoIndex) else {
        Panic("Write refused a buffer of FieldBound bytes")
    }
    try w.Str("enc ")
    try FzHex(w, out[0..m])
    try w.Str("\n")
    var dec2 := try fields.Decoder.New(h, 0, 1 << 20)
    defer dec2.Free(h)
    var back := FzRaw(bytes: HeapList[u8].New(h), spans: HeapList[FzSpan].New(h))
    defer back.Free(h)
    _ = dec2.Decode(h, mut back, out[0..m]) else {
        Panic("the re-encoded string does not decode")
    }
    if !FzSame(&raw, &back) {
        Panic("the re-encoded string decodes to another value")
    }
}

/// FzCheck parses fuzzed field pairs into a FieldBlock and runs CheckRequest,
/// CheckResponse, CheckTrailers, JoinCookies, Sendable and LowerName.
FzCheck(a: &Arena, h: &Alloc, w: mut Writer, input: []u8): WriteError|OutOfMemory!void {
    var fb := fields.FieldBlock.New(h)
    defer fb.Free(h)
    var at := 0
    for at + 1 < input.Len() && fb.Len() < 64 {
        var nl := int(input[at]) & 31
        var vl := int(input[at + 1]) & 63
        at += 2
        if nl > input.Len() - at {
            nl = input.Len() - at
        }
        name := input[at..at + nl]
        at += nl
        if vl > input.Len() - at {
            vl = input.Len() - at
        }
        val := input[at..at + vl]
        at += vl
        _ = fields.Sendable(name)
        lbuf := try a.Slice[u8](nl + 1)
        if fields.LowerName(name, val, mut lbuf[0..nl]) {
            Assert(nl > 0)
            for c in lbuf[0..nl] {
                Assert(c > 0x20 && !(c >= 0x41 && c <= 0x5A) && c < 0x7F && c != b':')
            }
        }
        try fb.Add(h, name, val, false, 0)
    }
    var req_ok := false
    match fields.CheckRequest(&fb) {
        ok(rh) {
            req_ok = true
            Assert(rh.method != "")
            if !rh.connect {
                Assert(rh.scheme == "http" || rh.scheme == "https")
                Assert(rh.path != "")
            } else {
                Assert(rh.authority != "")
            }
            for i in 0..fb.Len() {
                Assert(fb.Text(i).IsSome())
            }
            try w.Str("req ok\n")
        }
        err(_) { try w.Str("req err\n") }
    }
    _ = req_ok
    match fields.CheckResponse(&fb) {
        ok(r) {
            Assert(r.status >= 100 && r.status <= 999 && r.status != 101)
            try w.Str("resp ok\n")
        }
        err(_) { try w.Str("resp err\n") }
    }
    match fields.CheckTrailers(&fb) {
        ok(_) { try w.Str("trl ok\n") }
        err(_) { try w.Str("trl err\n") }
    }
    cbuf := try a.Slice[u8](fb.Bytes() + 8)
    _ = fields.JoinCookies(&fb, cbuf)
}

/// FzQpack exercises QDecoder.Instructions, Decode, Unblocked, Owed, Cancel,
/// QEncoder.EncodeBlock roundtrip, and QEncoder.PeerInstructions.
FzQpack(a: &Arena, h: &Alloc, w: mut Writer, input: []u8): WriteError|OutOfMemory!void {
    if input.Len() < 4 {
        try w.Str("short\n")
        return
    }
    cap := FzSizes[int(input[0] & 3)]
    max_blk := [0, 2, 16, 1][int((input[0] >> 2) & 3)]
    limit := FzLimits[int((input[0] >> 4) & 3)]
    rest := input[4..]
    c1 := int(input[1]) % (rest.Len() + 1)
    c2 := c1 + int(input[2]) % (rest.Len() - c1 + 1)
    c3 := c2 + int(input[3]) % (rest.Len() - c2 + 1)
    ins1 := rest[0..c1]
    ins2 := rest[c1..c2]
    sec := rest[c2..c3]
    peer := rest[c3..]

    var dec := try fields.QDecoder.New(h, cap, max_blk, limit)
    defer dec.Free(h)
    var fb := fields.FieldBlock.New(h)
    defer fb.Free(h)

    // First encoder-stream chunk (may end mid-instruction).
    match dec.Instructions(h, ins1) {
        ok(used) {
            Assert(used >= 0 && used <= ins1.Len())
            try Print(w, "ins {used}\n", (used))
        }
        err(e) {
            try Print(w, "err {e}\n", (e))
            return
        }
    }
    // Feed field section, possibly blocked.
    var blocked := false
    match dec.Decode(h, mut fb, 4, sec) {
        ok(o) {
            if o == fields.QOutcome.Blocked {
                blocked = true
                try w.Str("blocked\n")
            } else if o == fields.QOutcome.TooLarge {
                try w.Str("too large\n")
            } else {
                Assert(fb.Bytes() + 32 * fb.Len() <= limit)
                try Print(w, "ok {n}\n", (n: fb.Len()))
                qenc := fields.QEncoder.New()
                out := try a.Slice[u8](qenc.BlockBound(&fb))
                m := qenc.EncodeBlock(out, &fb) else {
                    Panic("EncodeBlock refused BlockBound bytes")
                }
                var dec2 := try fields.QDecoder.New(h, 0, 0, 1 << 20)
                defer dec2.Free(h)
                var fb2 := fields.FieldBlock.New(h)
                defer fb2.Free(h)
                o2 := dec2.Decode(h, mut fb2, 0, out[0..m]) else {
                    Panic("QEncoder roundtrip failed to decode")
                }
                Assert(o2 == fields.QOutcome.Fits && fb2.Len() == fb.Len())
                for i in 0..fb.Len() {
                    f1 := fb.Get(i)
                    f2 := fb2.Get(i)
                    Assert(f1.sensitive == f2.sensitive && FzEq(f1.name, f2.name) && FzEq(f1.value, f2.value))
                }
            }
        }
        err(e) {
            try Print(w, "err {e}\n", (e))
        }
    }
    // Second encoder-stream chunk, then Unblocked/Owed/Cancel.
    match dec.Instructions(h, ins2) {
        ok(used) {
            Assert(used >= 0 && used <= ins2.Len())
        }
        err(e) {
            try Print(w, "err {e}\n", (e))
        }
    }
    var unb: [16]i64 = [0; 16]
    _ = dec.Unblocked(mut unb[..])
    if blocked {
        dec.Cancel(4)
    }
    var owed: [64]u8 = [0; 64]
    _ = dec.Owed(mut owed[..])
    qenc := fields.QEncoder.New()
    match qenc.PeerInstructions(peer) {
        ok(u) { Assert(u >= 0 && u <= peer.Len()) }
        err(e) { try Print(w, "peer {e}\n", (e)) }
    }
}

/// Serves fuzz inputs on standard input until it ends.
export FieldsFuzzMain(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {
    var inp := sys.Stdin()
    var out := sys.Stdout()
    data := try sys.arena.Slice[u8](1 << 16)
    var head: [32]u8 = [0; 32]
    h := sys.heap.Alloc()
    for {
        k := try inp.Until(0x0A, mut head[..])
        if k == 0 {
            return
        }
        line := try str.From(head[0..k - 1])
        (after, before) := line.SplitOnce(" ").Must()
        n := Cast[int](try after.ParseInt())
        got := try inp.ReadAll(mut data[0..n])
        var ar := try Arena.New(sys.heap)
        defer ar.Free()
        if before == "h" {
            try FzHpack(&ar, h, mut out, data[0..got])
        } else if before == "c" {
            try FzCheck(&ar, h, mut out, data[0..got])
        } else if before == "q" {
            try FzQpack(&ar, h, mut out, data[0..got])
        } else {
            try FzHuffman(&ar, h, mut out, data[0..got])
        }
        try out.Str("END\n")
        try out.Flush()
    }
}
`

// hfServe is the driver program.
const hfServe = "import std.http\n\nexport Main(sys: &System): WriteError|OutOfMemory|ReadError|Utf8Error|ParseError!void {\n    try http.FieldsFuzzMain(sys)\n}\n"

// hfSrv is the running driver, shared by a fuzz worker's inputs.
var hfSrv struct {
	sync.Mutex
	cmd *exec.Cmd
	in  io.WriteCloser
	out *bufio.Reader
	err *bytes.Buffer
	// failed is the output of a driver build that failed, so later inputs
	// fail at once instead of building again.
	failed string
}

// hfAsk returns the driver's answer lines for in under mode, starting the
// driver first; a driver that dies fails the test with its stderr.
func hfAsk(t *testing.T, mode byte, in []byte) []string {
	t.Helper()
	hfSrv.Lock()
	defer hfSrv.Unlock()
	if hfSrv.failed != "" {
		t.Fatal(hfSrv.failed)
	}
	if hfSrv.cmd == nil {
		// Built outside t.TempDir, which ends with the test that made it,
		// while the driver serves every later input; TestMain removes it.
		dir, err := packageTempDir("mkhfz")
		if err != nil {
			t.Fatal(err)
		}
		stdDir := copyStd(t, dir, map[string]string{hfShimPath: hfShim})
		if err := os.WriteFile(filepath.Join(dir, "main.mk"), []byte(hfServe), 0o644); err != nil {
			t.Fatal(err)
		}
		exe := filepath.Join(dir, "hfz")
		if runtime.GOOS == "windows" {
			exe += ".exe"
		}
		t.Setenv("MK_CACHE", filepath.Join(dir, "cache"))
		out, status := mkCmd(t, dir, stdDir, "build", "--release", "-o", exe, "main.mk")
		if status != 0 {
			if strings.Contains(out, "no usable LLVM") {
				t.Skipf("needs the LLVM toolchain: %s", out)
			}
			hfSrv.failed = fmt.Sprintf("mk build: exit %d\n%s", status, out)
			t.Fatal(hfSrv.failed)
		}
		cmd := exec.Command(exe)
		stdin, err := cmd.StdinPipe()
		if err != nil {
			t.Fatal(err)
		}
		stdout, err := cmd.StdoutPipe()
		if err != nil {
			t.Fatal(err)
		}
		var eb bytes.Buffer
		cmd.Stderr = &eb
		if err := cmd.Start(); err != nil {
			t.Fatal(err)
		}
		hfSrv.cmd, hfSrv.in, hfSrv.out, hfSrv.err = cmd, stdin, bufio.NewReader(stdout), &eb
	}
	if _, err := fmt.Fprintf(hfSrv.in, "%c %d\n%s", mode, len(in), in); err != nil {
		hfDied(t, in, err)
	}
	var lines []string
	for {
		line, err := hfSrv.out.ReadString('\n')
		if err != nil {
			hfDied(t, in, err)
		}
		line = strings.TrimRight(line, "\r\n")
		if line == "END" {
			return lines
		}
		lines = append(lines, line)
	}
}

// hfDied reports a driver that stopped answering, and forgets it so the
// next input starts another.
func hfDied(t *testing.T, in []byte, err error) {
	t.Helper()
	msg := hfSrv.err.String()
	hfSrv.cmd = nil
	t.Fatalf("driver gone on input %x: %v\n%s", in, err, msg)
}

// hfStop ends the driver, so its executable can be removed.
func hfStop() {
	hfSrv.Lock()
	defer hfSrv.Unlock()
	if hfSrv.cmd == nil {
		return
	}
	hfSrv.in.Close()
	_ = hfSrv.cmd.Wait()
	hfSrv.cmd = nil
}

// hfUnhex decodes the tests' own hex dumps, spaces ignored.
func hfUnhex(s string) []byte {
	b, err := hex.DecodeString(strings.ReplaceAll(s, " ", ""))
	if err != nil {
		panic(err)
	}
	return b
}

