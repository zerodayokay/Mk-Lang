func FuzzStdHttpFields_Huffman(f *testing.F) {
	f.Cleanup(hfStop)
	for _, s := range []string{"www.example.com", "no-cache", "custom-key", "custom-value", "302", "307", "Mon, 21 Oct 2013 20:13:21 GMT", "https://www.example.com", "gzip", "foo=ASDJKHQKBZXOQWEOPIUAXQWEOIU; max-age=3600; version=1", ""} {
		f.Add(hfHuffEncodeRef([]byte(s)))
	}
	all := make([]byte, 256)
	for i := range all {
		all[i] = byte(255 - i)
	}
	f.Add(hfHuffEncodeRef(all))
	for _, s := range []string{"1fff", "1e", "ffffffff", "ff", "fe", "00"} {
		f.Add(hfUnhex(s))
	}
	f.Fuzz(func(t *testing.T, in []byte) {
		if len(in) > 4096 {
			in = in[:4096]
		}
		lines := hfAsk(t, 'u', in)
		want, err := hfHuffDecodeRef(in)
		if err != nil {
			if len(lines) != 1 || !strings.HasPrefix(lines[0], "err ") || !strings.Contains(lines[0], "BadHuffman(offset: 1)") {
				t.Fatalf("input %x: the model says %v, the decoder %q", in, err, lines)
			}
			return
		}
		if len(lines) != 2 || lines[0] != "ok "+hex.EncodeToString(want) || !strings.HasPrefix(lines[1], "enc ") {
			t.Fatalf("input %x: the model decodes %x, the decoder answers %q", in, want, lines)
		}
		enc, err := hex.DecodeString(lines[1][4:])
		// :path "/" and "/index.html" are static entries 4 and 5: one index byte.
		if err == nil && len(enc) == 1 && (enc[0] == 0x84 && string(want) == "/" || enc[0] == 0x85 && string(want) == "/index.html") {
			return
		}
		if err != nil || len(enc) < 2 || enc[0] != 0x04 {
			t.Fatalf("input %x: encoding %q", in, lines[1])
		}
		// The string's head, then its bytes: Huffman exactly when its code
		// is not longer than the raw bytes, and then the model's code.
		n, i := int(enc[1]&0x7f), 2
		if n == 0x7f {
			for m := 0; ; m += 7 {
				n += int(enc[i]&0x7f) << m
				i++
				if enc[i-1]&0x80 == 0 {
					break
				}
			}
		}
		body, code := enc[i:], hfHuffEncodeRef(want)
		if len(body) != n {
			t.Fatalf("input %x: encoding %x: length %d, %d bytes follow", in, enc, n, len(body))
		}
		if enc[1]&0x80 != 0 {
			if !bytes.Equal(body, code) || len(code) > len(want) {
				t.Fatalf("input %x: Huffman %x, the model codes %x for %d bytes", in, body, code, len(want))
			}
		} else if !bytes.Equal(body, want) || len(code) <= len(want) {
			t.Fatalf("input %x: raw %x for %x, whose code is %d bytes", in, body, want, len(code))
		}
	})
}

