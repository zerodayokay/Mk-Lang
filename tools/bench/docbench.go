// Why: a reader comparing Mk with C, Rust, Zig, Go and C# wants one page
// that says, for every row, what Mk measured before and after a change and
// how it stands against the fastest rival, with every number traceable to a
// published results file and nothing typed in by hand.
//
// What: writeBenchDoc renders doc/benchmarks.md from two results dates (a
// "before" and an "after"): the run facts of both, a before/after table per
// runtime table (startup, same, simd, idiomatic, app), the codegen kernels,
// the compile-speed cells, a scorecard against the bars, and the after
// date's hand-written NOTES.md (root causes of the rows still behind).
//
// How: `tools/bench render -doc -before D1 -after D2` loads
// tests/bench/results/<D>/{results.json,codegen,compile}/results.json. Mk's
// before/after change is the ratio of the two runs' medians with a bootstrap
// interval (ratioCI); every Mk-to-rival ratio uses the after run's own cells,
// so a rival is always compared within one run.

package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"math"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// docTables are the runtime tables of doc/benchmarks.md, in order, with the
// bar Mk's median is held to against the reference (0: no bar printed).
var docTables = []struct {
	name, ref string
	bar       float64
}{
	{"startup", "fastest other column", 0},
	{"same", "faster of rust-ovf and zig-safe (checked peers)", 1.00},
	{"simd", "fastest other column", 0},
	{"idiomatic", "fastest other column", 1.25},
	{"app", "fastest other column", 1.25},
}

// docSamePeers are the columns that check what Mk checks in the same table.
var docSamePeers = []string{"rust-ovf", "zig-safe"}

// readResultsIfAny loads a results file, or nil when it does not exist.
func readResultsIfAny(p string) (*results, error) {
	b, err := os.ReadFile(p)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var res results
	if err := json.Unmarshal(b, &res); err != nil {
		return nil, fmt.Errorf("%s: %w", p, err)
	}
	return &res, nil
}

// writeBenchDoc writes doc/benchmarks.md from the before and after dates.
func writeBenchDoc(root, before, after string) error {
	dir := func(d string) string { return filepath.Join(root, "tests", "bench", "results", d) }
	var b, a *results
	var err error
	if b, err = readResultsIfAny(filepath.Join(dir(before), "results.json")); err != nil {
		return err
	}
	if a, err = readResultsIfAny(filepath.Join(dir(after), "results.json")); err != nil {
		return err
	}
	if b == nil || a == nil {
		return fmt.Errorf("render -doc needs results.json under both %s and %s", before, after)
	}
	cgB, err := loadCodegenIfAny(root, before)
	if err != nil {
		return err
	}
	cgA, err := loadCodegenIfAny(root, after)
	if err != nil {
		return err
	}
	csB, err := loadCompileIfAny(root, before)
	if err != nil {
		return err
	}
	csA, err := loadCompileIfAny(root, after)
	if err != nil {
		return err
	}
	notes, err := os.ReadFile(filepath.Join(dir(after), "NOTES.md"))
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	var w strings.Builder
	fmt.Fprintf(&w, "# Mk benchmarks: before and after\n\n")
	fmt.Fprintf(&w, "Generated by `go run ./tools/bench render -doc -before %s -after %s` from `tests/bench/results/%s/` and `tests/bench/results/%s/`; every number below is read from those files. How rows are chosen, built and timed is in [tests/bench/README.md](../tests/bench/README.md); the full per-column tables of the after run are in [tests/bench/RESULTS.md](../tests/bench/RESULTS.md).\n\n", before, after, before, after)
	w.WriteString("Ratios are medians over medians with a 95% bootstrap interval in brackets; below 1.00 Mk is faster. \"Mk change\" compares Mk's own medians across the two runs (other columns are re-timed in each run, so every Mk-to-rival ratio uses one run's cells).\n\n")
	docFacts(&w, b, a, before, after)
	sc := &docScore{}
	for _, t := range docTables {
		docRuntime(&w, b, a, t.name, t.ref, t.bar, sc)
	}
	docCodegen(&w, cgB, cgA)
	docCompile(&w, csB, csA)
	docScorecard(&w, sc)
	if len(notes) > 0 {
		w.WriteString("## Notes from the after run\n\n")
		w.Write(notes)
		if !strings.HasSuffix(string(notes), "\n") {
			w.WriteString("\n")
		}
	}
	return os.WriteFile(filepath.Join(root, "doc", "benchmarks.md"), []byte(w.String()), 0o644)
}

// docFacts prints both runs' header facts side by side.
func docFacts(w *strings.Builder, b, a *results, before, after string) {
	fb, fa := b.Runs[len(b.Runs)-1], a.Runs[len(a.Runs)-1]
	w.WriteString("## Runs\n\n| | before | after |\n|---|---|---|\n")
	row := func(k, x, y string) {
		fmt.Fprintf(w, "| %s | %s | %s |\n", k, cellText(orDash(x)), cellText(orDash(y)))
	}
	row("results date", before, after)
	row("commit", fb.Commit, fa.Commit)
	row("dirty tree", fmt.Sprint(fb.Dirty), fmt.Sprint(fa.Dirty))
	row("provisional", fmt.Sprint(fb.Provisional), fmt.Sprint(fa.Provisional))
	row("mk sha256", fb.MkSHA256, fa.MkSHA256)
	row("CPU", fb.CPU, fa.CPU)
	row("OS", fb.OS, fa.OS)
	row("power scheme", fb.Power, fa.Power)
	row("sweeps x runs (results.json)", docSweeps(b), docSweeps(a))
	var langs []string
	for k := range fa.Versions {
		langs = append(langs, k)
	}
	slices.Sort(langs)
	for _, l := range langs {
		row(l, fb.Versions[l], fa.Versions[l])
	}
	row("busy at start", strings.Join(fb.Busy, ", "), strings.Join(fa.Busy, ", "))
	w.WriteString("\n")
}

// docSweeps is a results file's sweep count and runs per cell.
func docSweeps(r *results) string {
	n := 0
	for _, c := range r.Cells {
		n = max(n, c.Summary.N)
	}
	return fmt.Sprintf("%d sweeps, up to %d timed runs per cell", r.Sweeps, n)
}

// docCell is the timed cell of (row, col) in r, or nil.
func docCell(r *results, row, col string) *cell {
	for i := range r.Cells {
		c := &r.Cells[i]
		if c.Row == row && c.Col == col && c.Excluded == "" && len(c.Times) > 0 {
			return c
		}
	}
	return nil
}

// docIsMk reports whether a column is one of Mk's (mk, mk-wrap, budgets).
func docIsMk(col string) bool { return col == "mk" || strings.HasPrefix(col, "mk-") }

// docScore counts the rows at or under their bar, per table.
type docScore struct {
	tables []string
	under  map[string]int
	total  map[string]int
	behind map[string][]string
	vsC    struct{ under, under110, total int }
}

func (s *docScore) add(table string, ok bool, row string) {
	if s.under == nil {
		s.under, s.total, s.behind = map[string]int{}, map[string]int{}, map[string][]string{}
	}
	if s.total[table] == 0 {
		s.tables = append(s.tables, table)
	}
	s.total[table]++
	if ok {
		s.under[table]++
	} else {
		s.behind[table] = append(s.behind[table], row)
	}
}

// docRuntime prints one runtime table's before/after rows.
func docRuntime(w *strings.Builder, b, a *results, table, ref string, bar float64, sc *docScore) {
	var rows []rowInfo
	for _, r := range a.Rows {
		if r.Table == table && docCell(a, r.ID, "mk") != nil {
			rows = append(rows, r)
		}
	}
	if len(rows) == 0 {
		return
	}
	fmt.Fprintf(w, "## %s\n\nReference: %s.", table, ref)
	if bar > 0 {
		fmt.Fprintf(w, " Bar: Mk's median at most %.2fx the reference.", bar)
	}
	w.WriteString("\n\n")
	same := table == "same"
	if same {
		w.WriteString("| row | Mk before | Mk after | Mk change | C | Mk / C | best checked peer | Mk / peer |\n|---|---|---|---|---|---|---|---|\n")
	} else {
		w.WriteString("| row | Mk before | Mk after | Mk change | fastest other | Mk / fastest | Mk peak memory |\n|---|---|---|---|---|---|---|\n")
	}
	for _, r := range rows {
		mkA := docCell(a, r.ID, "mk")
		mkB := docCell(b, r.ID, "mk")
		before, change := "-", "-"
		if mkB != nil {
			before = fmtSec(mkB.Summary.Median)
			change = docChange(ratioTo(mkA, mkB))
		}
		var refCell *cell
		if same {
			refCell = bestOf(a.Cells, func(c cell) bool { return c.Row == r.ID && slices.Contains(docSamePeers, c.Col) })
		} else {
			refCell = bestOf(a.Cells, func(c cell) bool { return c.Row == r.ID && !docIsMk(c.Col) && c.Table == table })
		}
		re := ratioTo(mkA, refCell)
		if same {
			cC := docCell(a, r.ID, "c")
			ce := ratioTo(mkA, cC)
			fmt.Fprintf(w, "| %s | %s | %s | %s | %s | %s | %s | %s |\n", r.ID, before, fmtSec(mkA.Summary.Median), change,
				docSec(cC), fmtRatio(ce), docNamed(refCell), fmtRatio(re))
			if !math.IsNaN(ce.Ratio) {
				sc.vsC.total++
				if ce.Ratio <= 1.00 {
					sc.vsC.under++
				}
				if ce.Ratio <= 1.10 {
					sc.vsC.under110++
				}
			}
		} else {
			peak := "-"
			if mkA.Peak != nil && mkA.Peak.RSS > 0 {
				peak = fmt.Sprintf("%.1f MiB", float64(mkA.Peak.RSS)/(1<<20))
			}
			fmt.Fprintf(w, "| %s | %s | %s | %s | %s | %s | %s |\n", r.ID, before, fmtSec(mkA.Summary.Median), change,
				docNamed(refCell), fmtRatio(re), peak)
		}
		if bar > 0 && !math.IsNaN(re.Ratio) {
			sc.add(table, re.Ratio <= bar, fmt.Sprintf("%s (%.2f)", r.ID, re.Ratio))
		}
	}
	w.WriteString("\n")
}

// docChange prints a before/after ratio as a signed percentage with its
// interval: -12.3% means Mk's median fell by 12.3%.
func docChange(e ratioEntry) string {
	if math.IsNaN(e.Ratio) {
		return "-"
	}
	return fmt.Sprintf("%+.1f%% [%+.1f, %+.1f]", (e.Ratio-1)*100, (e.CI.Lo-1)*100, (e.CI.Hi-1)*100)
}

func docSec(c *cell) string {
	if c == nil {
		return "-"
	}
	return fmtSec(c.Summary.Median)
}

func docNamed(c *cell) string {
	if c == nil {
		return "-"
	}
	return c.Col + " " + fmtSec(c.Summary.Median)
}

// docCodegen prints the in-process kernels' Mk/C ratio before and after.
func docCodegen(w *strings.Builder, b, a *codegenResults) {
	if a == nil {
		return
	}
	w.WriteString("## codegen (in-process kernels)\n\nMk's time per kernel run over C's, both timed in one process (README \"codegen\").\n\n| kernel | Mk / C before | Mk / C after | Mk after | C after |\n|---|---|---|---|---|\n")
	for _, c := range a.Cells {
		if c.Excluded != "" {
			continue
		}
		before := "-"
		if b != nil {
			for _, x := range b.Cells {
				if x.Kernel == c.Kernel && x.Excluded == "" {
					before = fmtRatio(x.Ratio)
				}
			}
		}
		fmt.Fprintf(w, "| %s | %s | %s | %s | %s |\n", c.Kernel, before, fmtRatio(c.Ratio), fmtSec(c.MkSum.Median), fmtSec(c.CSum.Median))
	}
	w.WriteString("\n")
}

// docCompile prints Mk's compile-speed cells before and after beside the
// after run's Rust cell and the fastest language of each kind.
func docCompile(w *strings.Builder, b, a *compileResults) {
	if a == nil {
		return
	}
	fmt.Fprintf(w, "## compile speed\n\nThe generated %d x %d program (README \"compile\"), %d jobs; seconds per build.\n\n", a.Spec.Modules, a.Spec.Funcs, a.Jobs)
	w.WriteString("| profile | kind | Mk before | Mk after | Mk change | Rust after | Mk / Rust | fastest |\n|---|---|---|---|---|---|---|---|\n")
	find := func(r *compileResults, lang, prof, kind string) *compileCell {
		if r == nil {
			return nil
		}
		for i := range r.Cells {
			c := &r.Cells[i]
			if c.Lang == lang && c.Profile == prof && c.Kind == kind && c.Excluded == "" && len(c.Times) > 0 {
				return c
			}
		}
		return nil
	}
	for _, c := range a.Cells {
		if c.Lang != "mk" || c.Excluded != "" || len(c.Times) == 0 {
			continue
		}
		mb, rs := find(b, "mk", c.Profile, c.Kind), find(a, "rust", c.Profile, c.Kind)
		before, change, vsRust, rust := "-", "-", "-", "-"
		if mb != nil {
			before = fmtSec(mb.Sum.Median)
			change = docChange(ratioEntry{Ratio: c.Sum.Median / mb.Sum.Median, CI: ratioCI(c.Times, mb.Times)})
		}
		if rs != nil {
			rust = fmtSec(rs.Sum.Median)
			vsRust = fmtRatio(ratioEntry{Ratio: c.Sum.Median / rs.Sum.Median, CI: ratioCI(c.Times, rs.Times)})
		}
		var best *compileCell
		for i := range a.Cells {
			x := &a.Cells[i]
			if x.Profile == c.Profile && x.Kind == c.Kind && x.Excluded == "" && !x.Nothing && len(x.Times) > 0 && (best == nil || x.Sum.Median < best.Sum.Median) {
				best = x
			}
		}
		fastest := "-"
		if best != nil {
			fastest = best.Lang + " " + fmtSec(best.Sum.Median)
		}
		fmt.Fprintf(w, "| %s | %s | %s | %s | %s | %s | %s | %s |\n", c.Profile, c.Kind, before, fmtSec(c.Sum.Median), change, rust, vsRust, fastest)
	}
	w.WriteString("\n")
}

// docScorecard prints how many rows of each table meet the bar, and names
// the ones that do not.
func docScorecard(w *strings.Builder, sc *docScore) {
	w.WriteString("## Scorecard (after)\n\n")
	if sc.vsC.total > 0 {
		fmt.Fprintf(w, "- same, Mk / C: %d of %d rows at or under 1.00, %d of %d at or under 1.10.\n", sc.vsC.under, sc.vsC.total, sc.vsC.under110, sc.vsC.total)
	}
	for _, t := range sc.tables {
		line := fmt.Sprintf("- %s: %d of %d rows at or under the bar", t, sc.under[t], sc.total[t])
		if len(sc.behind[t]) > 0 {
			line += "; behind: " + strings.Join(sc.behind[t], ", ")
		}
		w.WriteString(line + ".\n")
	}
	w.WriteString("\n")
}
